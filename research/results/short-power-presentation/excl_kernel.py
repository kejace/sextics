"""Wave-2 (excl lens): E1-kernel structure — exact kernel elements, exact membership certificates, generation by K_7.

Usage: python3 excl_kernel.py [dmax]  (default 9)
  1. K_7^±/J: representatives mod 2-3 primes -> rational reconstruction -> EXACT check A*D7 in J(F) by an exact
     numerator certificate N7 (N7(F) = A*D7 over Q, verified with Fractions). Gives dim_Q K_7^±/J_7^± >= 1 (with
     the modular upper bound 1 => exactly 1).  Also records the structural fact D7^+ in Q[X0,X1,X2,M], D7^- in Q[Y,L].
  2. For d = 8..dmax: K_d^±/J basis mod p; rank test whether S_{d-7} * {D7^+, D7^-} spans K_d/J (ideal generated by K_7).
  3. lambda-only relaxations (w = 0) for the kernel families at d = 8..dmax: Sum lam_a lam_b B_{D_a}(N_b) in J_{2d}
     (tiny msolve systems) -> candidate D's in the span of the kernel with vanishing relaxed defect.
Outputs: excl_kernel_D7.json (exact D7^±, N7^±), excl_kernel.out, log lines.
"""
import sys, time, json, os, subprocess
sys.path.insert(0, '/tmp/hodge/results/short-power-presentation')
import excl_lib as W
from hodge import core
from hodge.core import NV, monomials, shift, mul, add, sub, scale, pderiv, reduce_mod
from flint import nmod_mat
from fractions import Fraction

job = os.environ.get('W2JOB', 'excl_kernel')
dmax = int(sys.argv[1]) if len(sys.argv) > 1 else 9
F, A, q, rec = W.load()
t00 = time.time()

# ---- 1. exact D7^± ---------------------------------------------------------------------------
exact = {}
for par in [0, 1]:
    reps = []
    infos = []
    D7 = None
    nprimes = 0
    for p in W.PRIMES30[:6]:
        info, basis = W.e1_kernel(F, A, 7, par, p, want_basis=True)
        infos.append(info)
        assert info['hilbert_ok'] and info['kernel mod J'] == 1 and len(basis) == 1, info
        reps.append((p, basis))
        print(f'  parity {par}: kernel basis mod {p} done ({time.time()-t00:.0f}s)', flush=True)
        if len(reps) >= 2:
            lifted = W.lift_polys(reps)
            if lifted is not None:
                # verify the lift modulo a fresh prime before accepting
                pchk = W.PRIMES31[0]
                infoc, basisc = W.e1_kernel(F, A, 7, par, pchk, want_basis=True)
                same = (reduce_mod(lifted[0], pchk) == basisc[0])
                print(f'  parity {par}: lift with {len(reps)} primes verified mod {pchk}: {same}', flush=True)
                if same:
                    D7 = lifted[0]; nprimes = len(reps)
                    break
    assert D7 is not None, 'rational reconstruction of D7 failed'
    # exact membership certificate for A*D7
    AD = mul(A, D7)
    N7, minfo = W.exact_membership(F, AD, primes=W.PRIMES31, max_primes=5)
    assert N7 is not None, ('exact membership failed', minfo)
    # structural check: Y-dependence only via M (even) / X-dependence only via L (odd)
    if par == 0:
        dY = [pderiv(D7, i) for i in range(3, 6)]
        struct = (sub(dY[1], scale(dY[0], 3)) == {}) and (sub(dY[2], scale(dY[0], 5)) == {})
        structnote = 'D7^+ depends on Y only through M=Y0+3Y1+5Y2: ' + str(struct)
    else:
        dX = [pderiv(D7, i) for i in range(3)]
        struct = (sub(dX[1], scale(dX[0], 2)) == {}) and (sub(dX[2], scale(dX[0], 3)) == {})
        structnote = 'D7^- depends on X only through L=X0+2X1+3X2: ' + str(struct)
    exact[par] = {'D': core.to_str(D7), 'N': [core.to_str(n) for n in N7], 'nterms': len(D7), 'primes_lift': nprimes,
                  'membership_primes': minfo.get('primes'), 'struct': struct}
    W.wlog(exp='kernel-exact-D7', d=7, parD=par, prime=[p for p, _ in reps], result='exact: A*D7 in J(F) over Q (certificate N7 verified with Fractions)',
           rank=infos[0]['rank J_{d+6}'], seconds=round(time.time() - t00, 1), job=job,
           note=f'dim_Q K_7/J = 1 exactly (modular bound 1 with 3 good primes + exact element); {structnote}; D7 has {len(D7)} terms')
    print('exact D7 parity', par, 'done', round(time.time() - t00), 's', flush=True)
with open(os.path.join(W.RES, 'excl_kernel_D7.json'), 'w') as f:
    json.dump(exact, f, indent=1)

# ---- 2. higher kernels, generation by K_7, lambda-only relaxations ------------------------------
p = W.PRIMES30[0]
Fp, Ap = reduce_mod(F, p), reduce_mod(A, p)
D7p = {par: reduce_mod(core.parse(exact[par]['D']), p) for par in [0, 1]}
N7p = {par: [reduce_mod(core.parse(s), p) for s in exact[par]['N']] for par in [0, 1]}
for d in range(8, dmax + 1):
    for par in [0, 1]:
        t0 = time.time()
        info, basis = W.e1_kernel(F, A, d, par, p, want_basis=True)
        k = info['kernel mod J']
        red = W.JReducer(Fp, d, par, p)
        # products m * D7^{par'} with deg m = d-7 and parity par - par'
        prods = []
        for par7 in [0, 1]:
            for m in monomials(d - 7, (par - par7) % 2):
                prods.append(shift(D7p[par7], m, 1, p))
        nf_prods = [red.normal_form_vec(P) for P in prods]
        nf_basis = [red.normal_form_vec(B) for B in (basis or [])]
        idx = {m: i for i, m in enumerate(red.mons)}
        rk_prods = W.rows_matrix(nf_prods, idx, p).rank() if nf_prods else 0
        rk_all = W.rows_matrix(nf_prods + nf_basis, idx, p).rank() if (nf_prods or nf_basis) else 0
        generated = (rk_prods == k == rk_all)
        W.wlog(exp='kernel-generation', d=d, parD=par, prime=p, result=k, rank=info['rank J_{d+6}'], hilbert_ok=info['hilbert_ok'],
               rank_products=rk_prods, rank_products_plus_kernel=rk_all, generated_by_K7=generated,
               seconds=round(time.time() - t0, 1), job=job,
               note='kernel mod J = result; rank of S_{d-7}*{D7+,D7-} mod J_d = rank_products; generated_by_K7 means K_d/J_d = S_{d-7} K_7')
        print(f'd={d} par={par}: kernel mod J {k}, products rank {rk_prods}, union rank {rk_all}, generated {generated} [{time.time()-t0:.0f}s]', flush=True)
        # lambda-only relaxation on the kernel basis (w = 0)
        if basis:
            t1 = time.time()
            kern = []
            for Da in basis:
                Na, _ = W.membership_mod_p(Fp, mul(Ap, Da, p), p)
                kern.append((Da, Na))
            sysd = W.build_relaxation(F, A, d, kern, [], p, slice_euler=False, verbose=False)
            base = os.path.join(W.RES, f'excl_kernel_lamonly_d{d}p{par}')
            W.write_msolve(sysd, base + '.ms', p)
            W.write_singular(sysd, base + '.sing', p)
            with open(base + '.sing.out', 'w') as f:
                subprocess.run(['Singular', '-q', base + '.sing'], stdout=f, stderr=subprocess.STDOUT, timeout=3600)
            txt = open(base + '.sing.out').read()
            import re
            dim = re.search(r'dim = (.*)', txt); vdim = re.search(r'vdim = (.*)', txt); hv = re.search(r'hilb1 = (.*)', txt)
            W.wlog(exp='kernel-lambda-only-relaxation', d=d, parD=par, prime=p, unknowns=len(kern), equations=len(sysd['eqs']),
                   result=('proj-empty' if dim and dim.group(1).strip() == '0' else 'affine-dim-' + (dim.group(1).strip() if dim else '?')),
                   vdim=vdim.group(1).strip() if vdim else None, hilb1=hv.group(1).strip() if hv else None,
                   seconds=round(time.time() - t1, 1), job=job,
                   note='relaxed E2 defect for D in span(K_d/J_d basis) (w = 0): proj-empty => no such D works (rigorous for that family)')
            print(f'  lambda-only d={d} par={par}: {txt[-200:]!r}', flush=True)
print('all done', round(time.time() - t00), 's', flush=True)
