class SectorVarPro(varpro.VarProFamily):
    """VarProFamily whose numerator/quotient unknowns are restricted to the character sector forced by (A, D)."""

    def __init__(self, inst, basis, exclude_F_multiples=True, verbose=False, cond=1e-9):
        t0 = time.time()
        F, A, q = inst.F, inst.A, inst.q
        self.inst = inst
        self.cond = cond
        self.F, self.A, self.q = F, A, q
        self.basis = [dict(B) for B in basis]
        K = len(basis)
        self.K = K
        degs = {core.degree(B) for B in basis}
        if len(degs) != 1:
            raise ValueError('family members must share one degree')
        d = degs.pop(); self.d = d
        pars = {core.parity_of(B) for B in basis}
        if len(pars) != 1 or None in pars:
            raise ValueError('family members must share one pure Y-parity')
        self.pD = pars.pop()
        labs = {label_of_poly(inst, B) for B in basis}
        if len(labs) != 1 or None in labs:
            raise ValueError('family members must share one character label')
        self.lab = labs.pop()
        D0 = self.basis[0]
        allowed, sub = symmetry.sector_filter(F, A, q, D0, inst.G)
        self.subgroup_size = len(sub)
        self.pars = fixed_d.numerator_parities(D0, A)
        degN = d + 6 * q - 5; degQ = 2 * d - 6
        self.degN, self.degQ = degN, degQ
        Ncols = []
        self.full_nN = 0
        for i in range(NV):
            ms = monomials(degN, self.pars[i])
            self.full_nN += len(ms)
            Ncols += [(i, m) for m in symmetry.filter_monomials(ms, 'N', i, allowed)]
        if degQ >= 0:
            ms = monomials(degQ, core.parity_of(A))
            self.full_nQ = len(ms)
            Qcols = symmetry.filter_monomials(ms, 'Q', -1, allowed)
        else:
            self.full_nQ = 0
            Qcols = []
        self.Ncols, self.Qcols = Ncols, Qcols
        self.nN, self.nQ = len(Ncols), len(Qcols)
        Fi = [pderiv(F, i) for i in range(NV)]
        Fq1 = scale(power(F, q + 1), -1)
        rows = {}

        def ridx(e):
            if e not in rows:
                rows[e] = len(rows)
            return rows[e]
        blocks = []
        for Bk in self.basis:
            FBk = mul(F, Bk)
            Bki = [pderiv(Bk, i) for i in range(NV)]
            G = [scale(add(scale(mul(Bk, Fi[i]), q), mul(F, Bki[i])), -1) for i in range(NV)]
            ri, ci, vals = [], [], []
            for j, (i, m) in enumerate(Ncols):
                col = shift(G[i], m, 1)
                if m[i]:
                    m2 = list(m); m2[i] -= 1
                    col = add(col, shift(FBk, tuple(m2), m[i]))
                for e, v in col.items():
                    ri.append(ridx(e)); ci.append(j); vals.append(float(v))
            blocks.append((ri, ci, vals))
        qri, qci, qvals = [], [], []
        for j, m in enumerate(Qcols):
            col = shift(Fq1, m, 1)
            for e, v in col.items():
                qri.append(ridx(e)); qci.append(j); qvals.append(float(v))
        AB = [mul(A, Bk) for Bk in self.basis]
        pair = {}
        for k in range(K):
            for l in range(k, K):
                v = scale(mul(AB[k], self.basis[l]), -1)
                pair[(k, l)] = v
                for e in v:
                    ridx(e)
        R = len(rows)
        self.rows = R
        self.row_index = rows
        self.Mk = [sp.csr_matrix((np.array(vals), (np.array(ri, dtype=np.int64), np.array(ci, dtype=np.int64))),
                                 shape=(R, self.nN)) for ri, ci, vals in blocks]
        self.MQ = sp.csr_matrix((np.array(qvals), (np.array(qri, dtype=np.int64), np.array(qci, dtype=np.int64))),
                                shape=(R, self.nQ)).toarray() if self.nQ else np.zeros((R, 0))
        self.Vk = []
        for k in range(K):
            ri, ci, vals = [], [], []
            for l in range(K):
                v = pair[(min(k, l), max(k, l))]
                for e, c in v.items():
                    ri.append(rows[e]); ci.append(l); vals.append(float(c))
            self.Vk.append(sp.csr_matrix((np.array(vals), (np.array(ri, dtype=np.int64), np.array(ci, dtype=np.int64))),
                                         shape=(R, K)))
        self.ncols = self.nN + self.nQ
        self.P = np.eye(K)
        self.excluded_dim = 0
        if exclude_F_multiples and d >= 6:
            self.P, self.excluded_dim = self._complement_of_F_multiples()
        self.dimP = self.P.shape[1]
        self.build_time = time.time() - t0
        self._nfev = 0
        if verbose:
            print(f'[sectorvarpro] d={d} lab={self.lab} K={K} dimP={self.dimP} rows={R} cols={self.ncols} '
                  f'(N {self.nN}/{self.full_nN}, Q {self.nQ}/{self.full_nQ}) excluded F-mult dim={self.excluded_dim} '
                  f'built in {self.build_time:.1f}s', file=sys.stderr)

    def D_float(self, a):
        a = np.asarray(a, float)
        D = {}
        for k, B in enumerate(self.basis):
            if a[k] == 0:
                continue
            for e, v in B.items():
                D[e] = D.get(e, 0.0) + a[k] * float(v)
        return {e: v for e, v in D.items() if abs(v) > 1e-15}

    def coords_of(self, Dpoly):
        """Least-squares coordinates of a poly in the family basis and the relative residual of the projection."""
        M, rows = _dense(self.basis)
        b = np.zeros(len(rows) + 0)
        extra = [e for e in Dpoly if e not in rows]
        if extra:
            M = np.vstack([M, np.zeros((len(extra), self.K))])
            for e in extra:
                rows[e] = len(rows)
            b = np.zeros(len(rows))
        for e, v in Dpoly.items():
            b[rows[e]] = float(v)
        x, *_ = sla.lstsq(M, b)
        rel = np.linalg.norm(M @ x - b) / max(np.linalg.norm(b), 1e-300)
        return x, float(rel)

    def polish(self, a, maxiter=3000, gtol=1e-16):
        """Re-minimize from a with tighter tolerances; returns (a, rel)."""
        from scipy.optimize import minimize
        u0 = self.P.T @ np.asarray(a, float)
        u0 /= max(np.linalg.norm(u0), 1e-300)
        res = minimize(self.value_and_grad, u0, jac=True, method='L-BFGS-B',
                       options={'maxiter': maxiter, 'gtol': gtol, 'ftol': 1e-18, 'maxcor': 30})
        a1 = self.P @ res.x; a1 /= np.linalg.norm(a1)
        f, x, r = self.value(a1)
        bn = self.bnorm(a1)
        return a1, f / max(bn * bn, 1e-300)

    def grid_scan(self, npts=720):
        """dimP == 2: scan the circle; dimP == 1: single point. Returns list of (rel, a)."""
        out = []
        if self.dimP == 1:
            a = self.P[:, 0]
            f, x, r = self.value(a); bn = self.bnorm(a)
            out.append((f / max(bn * bn, 1e-300), a))
        elif self.dimP == 2:
            for t in np.linspace(0, np.pi, npts, endpoint=False):
                a = self.P @ np.array([np.cos(t), np.sin(t)])
                f, x, r = self.value(a); bn = self.bnorm(a)
                out.append((f / max(bn * bn, 1e-300), a))
        out.sort(key=lambda z: z[0])
        return out


class HessRelax:
    """Hessian relaxation on the w-space: D = sum_k a_k m_k F_{i_k}, N = A w (w_k = m_k e_{i_k}), no Koszul correction.
    E2 then reads  D div(A w) - (A w)(D) = F Q  (deg Q = 2d-6).  Residual r(a) = V(a,a) - MQ x, f(a) = min_x |r|^2.
    A zero of f gives a genuine certificate with N = A w (no E1 unknowns needed); failure excludes nothing."""

    def __init__(self, inst, d, lab, verbose=False):
        t0 = time.time()
        F, A, q = inst.F, inst.A, inst.q
        assert q == 1
        self.inst, self.d, self.lab = inst, d, lab
        items = []  # (i, m)
        for i in range(NV):
            ml = inst.sublab(lab, inst.labFi[i])
            for m in monomials(d - 5):
                if inst.label(m) == ml:
                    items.append((i, m))
        self.items = items
        K = len(items); self.K = K
        if K == 0:
            self.dimP = 0; return
        Dk = [shift(inst.Fi[i], m, 1) for i, m in items]
        self.Dk = Dk
        Am = [mul(A, {m: Fraction(1)}) for i, m in items]
        rows = {}

        def ridx(e):
            if e not in rows:
                rows[e] = len(rows)
            return rows[e]
        # v_kl = D_k * d_{i_l}(A m_l) - A m_l * d_{i_l}(D_k)
        pair = {}
        for k in range(K):
            for l in range(K):
                il = items[l][0]
                v = sub(mul(Dk[k], pderiv(Am[l], il)), mul(Am[l], pderiv(Dk[k], il)))
                pair[(k, l)] = v
                for e in v:
                    ridx(e)
        labQ = inst.addlab(inst.labA, lab, lab)
        degQ = 2 * d - 6
        Qm = [m for m in monomials(degQ) if inst.label(m) == labQ] if degQ >= 0 else []
        FQ = [shift(F, m, 1) for m in Qm]
        for P in FQ:
            for e in P:
                ridx(e)
        R = len(rows); self.rows = R
        MQ = np.zeros((R, len(Qm)))
        for j, P in enumerate(FQ):
            for e, v in P.items():
                MQ[rows[e], j] = float(v)
        # orthonormal basis of col(MQ): projector
        if len(Qm):
            U, s, _ = np.linalg.svd(MQ, full_matrices=False)
            r = int(np.sum(s > 1e-10 * s[0]))
            self.QQ = U[:, :r]
        else:
            self.QQ = np.zeros((R, 0))
        self.nQ = len(Qm)
        # symmetrized pair tensors: W_k = (R x K), column l = v_kl + v_lk
        self.Wk = []
        for k in range(K):
            ri, ci, vals = [], [], []
            for l in range(K):
                v = add(pair[(k, l)], pair[(l, k)])
                for e, c in v.items():
                    ri.append(rows[e]); ci.append(l); vals.append(float(c))
            self.Wk.append(sp.csr_matrix((np.array(vals), (np.array(ri, dtype=np.int64), np.array(ci, dtype=np.int64))), shape=(R, K)))
        # exclude F-multiples: D(a) in F S_{d-6}: solve [Dk | F m] nullspace
        self.P = np.eye(K); self.excluded_dim = 0
        if d >= 6:
            Gm = inst.sector_monomials(d - 6, lab)
            Fcols = [shift(F, m, 1) for m in Gm]
            Mb, _ = _dense(Dk + [scale(C, -1) for C in Fcols])
            ns = sla.null_space(Mb)
            S = ns[:K, :] if ns.size else np.zeros((K, 0))
            if S.shape[1]:
                U, s, _ = np.linalg.svd(S, full_matrices=True)
                r = int(np.sum(s > 1e-10 * max(1.0, s[0])))
                self.P, self.excluded_dim = U[:, r:], r
        self.dimP = self.P.shape[1]
        self.build_time = time.time() - t0
        if verbose:
            print(f'[hessrelax] d={d} lab={lab} K={K} dimP={self.dimP} rows={R} nQ={self.nQ} built {self.build_time:.1f}s', file=sys.stderr)

    def _Vaa(self, a):
        # V(a,a) = 1/2 sum_k a_k (W_k a)
        v = np.zeros(self.rows)
        for k in range(self.K):
            if a[k]:
                v += a[k] * (self.Wk[k] @ a)
        return 0.5 * v

    def value(self, a):
        a = np.asarray(a, float); a = a / np.linalg.norm(a)
        v = self._Vaa(a)
        r = v - self.QQ @ (self.QQ.T @ v)
        return float(r @ r), float(v @ v)

    def value_and_grad(self, u):
        a_full = self.P @ u
        na = np.linalg.norm(a_full); a = a_full / na
        v = self._Vaa(a)
        r = v - self.QQ @ (self.QQ.T @ v)
        f = float(r @ r)
        # d v / d a_k = W_k a  (symmetrized)  -> grad_k = 2 r . (W_k a)
        g = np.array([2.0 * float(r @ (self.Wk[k] @ a)) for k in range(self.K)])
        g_full = (g - float(g @ a) * a) / na
        return f, self.P.T @ g_full

    def search(self, n_restarts=100, seed=0, maxiter=500):
        from scipy.optimize import minimize
        rng = np.random.default_rng(seed)
        out = []
        for it in range(n_restarts):
            u0 = rng.standard_normal(self.dimP); u0 /= np.linalg.norm(u0)
            res = minimize(self.value_and_grad, u0, jac=True, method='L-BFGS-B',
                           options={'maxiter': maxiter, 'gtol': 1e-12, 'ftol': 1e-16})
            a = self.P @ res.x; a /= np.linalg.norm(a)
            f, vv = self.value(a)
            out.append({'value': f, 'rel': f / max(vv, 1e-300), 'a': a, 'iters': int(res.nit), 'restart': it})
        out.sort(key=lambda c: c['rel'])
        return out

    def D_float(self, a):
        D = {}
        for k, B in enumerate(self.Dk):
            if a[k] == 0:
                continue
            for e, v in B.items():
                D[e] = D.get(e, 0.0) + a[k] * float(v)
        return {e: v for e, v in D.items() if abs(v) > 1e-15}


