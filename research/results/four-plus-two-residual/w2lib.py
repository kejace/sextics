def rational_candidates(Dfl, max_dens=(1, 2, 3, 4, 6, 7, 12, 14, 21, 42, 84, 210, 420, 10**3, 10**4, 10**5, 10**6)):
    """Normalize D (largest |coefficient| -> 1) and propose exact rational versions with growing denominators.
    Yields (max_den, err, Dfrac)."""
    if not Dfl:
        return
    j = max(Dfl, key=lambda e: abs(Dfl[e]))
    cj = Dfl[j]
    Dn = {e: v / cj for e, v in Dfl.items()}
    seen = set()
    for md in max_dens:
        fr = {e: Fraction(v).limit_denominator(md) for e, v in Dn.items()}
        err = max(abs(float(fr[e]) - Dn[e]) for e in Dn)
        key = tuple(sorted((e, f) for e, f in fr.items() if f != 0))
        if key in seen:
            continue
        seen.add(key)
        Dfrac = {e: f for e, f in fr.items() if f != 0}
        yield md, err, Dfrac
    # common-denominator scaling
    vals = np.array([Dn[e] for e in Dn])
    for den in range(1, 5000):
        v = vals * den
        if np.max(np.abs(v - np.round(v))) < 1e-6 * den:
            Dfrac = {e: Fraction(int(round(x)), den) for e, x in zip(Dn, v) if int(round(x))}
            key = tuple(sorted(Dfrac.items()))
            if key not in seen:
                yield den, float(np.max(np.abs(v - np.round(v))) / den), Dfrac
            break


def confirm_exact(inst, Dfrac, verbose=False, compressed=False):
    """Exact certificate attempt for a rational D: E1 test, then the sector-restricted fixed-D solve with CRT lifting."""
    F, A, q = inst.F, inst.A, inst.q
    if not Dfrac:
        return 'inconsistent', {'note': 'D = 0'}
    divF, _ = jacobian.divisible_by(F, Dfrac) if core.degree(Dfrac) >= 6 else (False, None)
    if divF:
        return 'spurious', {'note': 'F divides D'}
    ok, info = fixed_d.e1_solvable(F, A, q, Dfrac)
    if not ok:
        return 'e1-fail', {'e1': {k: info[k] for k in ('rank', 'rank_aug', 'rows', 'cols')}}
    status, data = symmetry.solve_fixed_D_symmetric(F, A, q, Dfrac, verbose=verbose, group=inst.G, compressed=compressed)
    out = {k: data.get(k) for k in ('rank', 'nullity', 'rows', 'cols', 'full_cols', 'subgroup_size', 'primes_used', 'prime')}
    if status == 'solved':
        N, Q = data['N'], data['Q']
        ok2, info2 = core.verify_witness(F, A, q, Dfrac, N, Q)
        out['verified'] = bool(ok2)
        out['N'] = N; out['Q'] = Q
    return status, out


def save_witness(inst, D, N, Q, path=None, extra=None):
    path = path or f'{LANE}/witness-candidate.json'
    ok, info = core.verify_witness(inst.F, inst.A, inst.q, D, N, Q)
    divF, _ = jacobian.divisible_by(inst.F, D) if core.degree(D) >= 6 else (False, None)
    w = {'instance': inst.iid, 'd': core.degree(D), 'D': core.to_str(D), 'N': [core.to_str(n) for n in N],
         'Q': core.to_str(Q), 'verified': bool(ok), 'F_divides_D': bool(divF), 'info': str(info), 'engine': ENGINE}
    if extra:
        w.update(extra)
    with open(path, 'w') as f:
        json.dump(w, f, indent=1)
    return w


def reconstruct_and_confirm(inst, Dfl, log_path=None, tag='', verbose=False, max_tries=20):
    """Try rational reconstructions of a float D of increasing height; exact re-solve each; returns list of attempt records."""
    attempts = []
    for k, (md, err, Dfrac) in enumerate(rational_candidates(Dfl)):
        if k >= max_tries:
            break
        t0 = time.time()
        try:
            status, data = confirm_exact(inst, Dfrac, verbose=verbose)
        except Exception as ex:
            status, data = 'error', {'note': f'{ex.__class__.__name__}: {ex}'}
        rec = {'kind': 'reconstruct', 'tag': tag, 'max_den': md, 'recon_err': err, 'status': status,
               'D': core.to_str(Dfrac)[:4000], 'd': core.degree(Dfrac), 'nterms': len(Dfrac),
               'rank': data.get('rank'), 'nullity': data.get('nullity'), 'rows': data.get('rows'), 'cols': data.get('cols'),
               'seconds': round(time.time() - t0, 2), 'engine': ENGINE}
        if status == 'solved':
            w = save_witness(inst, Dfrac, data['N'], data['Q'], extra={'tag': tag})
            rec['witness_saved'] = True
            rec['verified'] = w['verified']
        attempts.append(rec)
        if log_path:
            log_line(log_path, rec)
        if status == 'solved':
            break
    return attempts
