class SectorVarPro:
    """Variable projection for a linear family D(a) = sum_k a_k B_k inside one character sector of S_d, with the N, Q
    unknowns restricted to the sector forced by (A, D) (lossless by averaging over the stabilizer).

    Parametrization: c = Bmat a are the coefficients of D in the sector monomials m_j (K0 of them);
    M(a) = sum_j c_j M^(j) with M^(j) the sparse fixed-D system matrix of the monomial denominator m_j
    (stored stacked: MstackT, shape (R*nN, K0)); b(a) = -A D^2 = Z (c kron c).
    f(a) = min_x |M(a) x - b(a)|^2 on the unit sphere, gradient by the Golub-Pereyra formula (engine convention)."""

    def __init__(self, inst, d, lab, basis, exclude_F_multiples=True, verbose=False, cond=1e-9):
        t0 = time.time()
        F, A, q = inst.F, inst.A, inst.q
        self.inst, self.d, self.lab, self.q = inst, d, lab, q
        self.F, self.A = F, A
        self.cond = cond
        Dm = inst.sector_monomials(d, lab)
        self.Dm = Dm
        K0 = len(Dm); self.K0 = K0
        didx = {m: j for j, m in enumerate(Dm)}
        K = len(basis); self.K = K
        Bmat = np.zeros((K0, K))
        for k, B in enumerate(basis):
            for e, v in B.items():
                Bmat[didx[e], k] = float(v)
        self.Bmat = Bmat
        self.basis = [dict(B) for B in basis]
        D0 = {Dm[0]: 1}
        self.pD = core.parity_of(D0)
        allowed, sub = symmetry.sector_filter(F, A, q, D0, inst.Gsub)
        self.subgroup_size = len(sub)
        self.pars = fixed_d.numerator_parities(D0, A)
        degN = d + 6 * q - 5; degQ = 2 * d - 6
        self.degN, self.degQ = degN, degQ
        Ncols = []
        self.full_nN = 0
        for i in range(NV):
            ms = monomials(degN, self.pars[i])
            self.full_nN += len(ms)
            Ncols += [(i, m) for m in symmetry.filter_monomials(ms, 'N', i, allowed)]
        if degQ >= 0:
            ms = monomials(degQ, core.parity_of(A))
            self.full_nQ = len(ms)
            Qcols = symmetry.filter_monomials(ms, 'Q', -1, allowed)
        else:
            self.full_nQ = 0; Qcols = []
        self.Ncols, self.Qcols = Ncols, Qcols
        nN, nQ = len(Ncols), len(Qcols)
        self.nN, self.nQ = nN, nQ
        Fi = [pderiv(F, i) for i in range(NV)]
        Fq1 = scale(power(F, q + 1), -1)
        rows = {}

        def ridx(e):
            v = rows.get(e)
            if v is None:
                v = len(rows); rows[e] = v
            return v
        # Q block (constant)
        qri, qci, qvals = [], [], []
        for j, m in enumerate(Qcols):
            for e, v in shift(Fq1, m, 1).items():
                qri.append(ridx(e)); qci.append(j); qvals.append(float(v))
        # N blocks per sector monomial m_j
        rj, rc, rnu, vals = [], [], [], []
        for j, mj in enumerate(Dm):
            mjp = {mj: Fraction(1)}
            Fmj = mul(F, mjp)
            Gj = [scale(add(scale(mul(mjp, Fi[i]), q), mul(F, pderiv(mjp, i))), -1) for i in range(NV)]  # -(q m_j F_i + F d_i m_j)
            for nu, (i, m) in enumerate(Ncols):
                col = shift(Gj[i], m, 1)
                if m[i]:
                    m2 = list(m); m2[i] -= 1
                    col = add(col, shift(Fmj, tuple(m2), m[i]))
                for e, v in col.items():
                    rj.append(j); rc.append(ridx(e)); rnu.append(nu); vals.append(float(v))
        # pair block: Z[:, j*K0 + j'] = -A m_j m_j'
        zri, zci, zvals = [], [], []
        for j in range(K0):
            for jp in range(j, K0):
                P = scale(mul(A, {tuple(a + b for a, b in zip(Dm[j], Dm[jp])): Fraction(1)}), -1)
                for e, v in P.items():
                    r_ = ridx(e)
                    zri.append(r_); zci.append(j * K0 + jp); zvals.append(float(v))
                    if jp != j:
                        zri.append(r_); zci.append(jp * K0 + j); zvals.append(float(v))
        R = len(rows); self.rows = R; self.row_index = rows
        flat = np.array(rc, dtype=np.int64) * nN + np.array(rnu, dtype=np.int64)
        self.MstackT = sp.csr_matrix((np.array(vals), (flat, np.array(rj, dtype=np.int64))), shape=(R * nN, K0))
        self.Mstack = self.MstackT.T.tocsr()
        del rj, rc, rnu, vals, flat
        self.MQ = sp.csr_matrix((np.array(qvals), (np.array(qri, dtype=np.int64), np.array(qci, dtype=np.int64))),
                                shape=(R, nQ)).toarray() if nQ else np.zeros((R, 0))
        self.Z = sp.csr_matrix((np.array(zvals), (np.array(zri, dtype=np.int64), np.array(zci, dtype=np.int64))),
                               shape=(R, K0 * K0))
        self.ncols = nN + nQ
        # F-multiples inside the sector, in m_j coordinates
        self.QF = np.zeros((K0, 0)); self.excluded_dim = 0
        self.P = np.eye(K)
        if d >= 6:
            Gm = inst.sector_monomials(d - 6, lab)
            FM = np.zeros((K0, len(Gm)))
            for jj, g in enumerate(Gm):
                for e, v in shift(F, g, 1).items():
                    FM[didx[e], jj] = float(v)
            if len(Gm):
                U, s, _ = np.linalg.svd(FM, full_matrices=False)
                r = int(np.sum(s > 1e-10 * s[0]))
                self.QF = U[:, :r]
            if exclude_F_multiples and self.QF.shape[1]:
                # a with Bmat a in span(QF): nullspace of [Bmat | -QF]
                ns = sla.null_space(np.hstack([Bmat, -self.QF]))
                S = ns[:K, :] if ns.size else np.zeros((K, 0))
                if S.shape[1]:
                    U, s, _ = np.linalg.svd(S, full_matrices=True)
                    r = int(np.sum(s > 1e-10 * max(1.0, s[0])))
                    self.P, self.excluded_dim = U[:, r:], r
        self.dimP = self.P.shape[1]
        self.build_time = time.time() - t0
        self._nfev = 0
        if verbose:
            print(f'[sectorvarpro] d={d} lab={lab} K0={K0} K={K} dimP={self.dimP} rows={R} cols={self.ncols} '
                  f'(N {nN}/{self.full_nN}, Q {nQ}/{self.full_nQ}) nnz(Mstack)={self.MstackT.nnz} excluded F-mult dim={self.excluded_dim} '
                  f'built in {self.build_time:.1f}s', file=sys.stderr)

    # ------------------------------------------------------------------
    def coeffs(self, a):
        return self.Bmat @ np.asarray(a, float)

    def assemble(self, a):
        c = self.coeffs(a)
        M = (self.MstackT @ c).reshape(self.rows, self.nN)
        if self.nQ:
            M = np.hstack([M, self.MQ])
        b = self.Z @ np.outer(c, c).ravel()
        return M, b, c

    def value(self, a):
        a = np.asarray(a, dtype=float)
        na = np.linalg.norm(a)
        a = a / na
        M, b, c = self.assemble(a)
        x, *_ = sla.lstsq(M, b, cond=self.cond, lapack_driver='gelsd', check_finite=False)
        r = M @ x - b
        self._nfev += 1
        return float(r @ r), x, r

    def bnorm(self, a):
        a = np.asarray(a, float); a = a / np.linalg.norm(a)
        c = self.coeffs(a)
        return float(np.linalg.norm(self.Z @ np.outer(c, c).ravel()))

    def rel(self, a):
        f, x, r = self.value(a)
        bn = self.bnorm(a)
        return f / max(bn * bn, 1e-300)

    def value_and_grad(self, u):
        u = np.asarray(u, dtype=float)
        a_full = self.P @ u
        na = np.linalg.norm(a_full)
        a = a_full / na
        M, b, c = self.assemble(a)
        x, *_ = sla.lstsq(M, b, cond=self.cond, lapack_driver='gelsd', check_finite=False)
        r = M @ x - b
        f = float(r @ r)
        xN = x[:self.nN]
        gM = self.Mstack @ np.outer(r, xN).ravel()          # gM_j = r . (M^(j) x_N)
        W = (self.Z.T @ r).reshape(self.K0, self.K0)        # r . Z(c kron c) = c^T W c
        gb = (W + W.T) @ c                                  # d/dc of r.b
        gc = 2.0 * (gM - gb)
        g = self.Bmat.T @ gc
        g_full = (g - float(g @ a) * a) / na
        self._nfev += 1
        return f, self.P.T @ g_full

    # ------------------------------------------------------------------
    def is_spurious(self, a, tol=1e-8):
        if self.QF.shape[1] == 0:
            return False, 1.0
        c = self.coeffs(np.asarray(a, float) / np.linalg.norm(a))
        res = c - self.QF @ (self.QF.T @ c)
        rel = float(np.linalg.norm(res) / max(np.linalg.norm(c), 1e-300))
        return rel < tol, rel

    def search(self, n_restarts=10, seed=0, maxiter=300, gtol=1e-10, verbose=False, stop_rel=1e-13):
        from scipy.optimize import minimize
        rng = np.random.default_rng(seed)
        out = []
        t0 = time.time()
        for it in range(n_restarts):
            u0 = rng.standard_normal(self.dimP); u0 /= np.linalg.norm(u0)
            res = minimize(self.value_and_grad, u0, jac=True, method='L-BFGS-B',
                           options={'maxiter': maxiter, 'gtol': gtol, 'ftol': 1e-16})
            a = self.P @ res.x; a /= np.linalg.norm(a)
            f, x, r = self.value(a)
            bn = self.bnorm(a)
            rel = f / max(bn * bn, 1e-300)
            spur, srel = self.is_spurious(a)
            out.append({'value': f, 'rel': rel, 'a': a, 'spurious': spur, 'div_rel': srel, 'iters': int(res.nit), 'restart': it})
            if verbose:
                print(f'[sectorvarpro] restart {it}: f={f:.3e} rel={rel:.3e} iters={res.nit} spurious={spur} ({time.time()-t0:.1f}s)', file=sys.stderr)
            if rel < stop_rel and not spur:
                break
        out.sort(key=lambda c_: (c_['spurious'], c_['rel']))
        return out

    # ------------------------------------------------------------------
    # Levenberg-Marquardt variable projection (Kaufman Jacobian)
    def residual_and_jac(self, u):
        """r(u) = M(a)x(a) - b(a) at a = Pu/|Pu| with x the min-norm least-squares solution (SVD cutoff self.cond),
        and the Kaufman Jacobian  J = (I - U_r U_r^T) (dM/da x_N - db/da) da/du."""
        u = np.asarray(u, float)
        a_full = self.P @ u
        na = np.linalg.norm(a_full)
        a = a_full / na
        M, b, c = self.assemble(a)
        U, s, Vt = sla.svd(M, full_matrices=False, check_finite=False, lapack_driver='gesdd')
        keep = s > self.cond * (s[0] if s.size else 1.0)
        Ur = U[:, keep]
        x = Vt[keep].T @ ((Ur.T @ b) / s[keep])
        r = M @ x - b
        xN = x[:self.nN]
        K0 = self.K0
        Kx = sp.kron(sp.eye(self.rows, format='csr'), sp.csr_matrix(xN[None, :]), format='csr')
        Y = (Kx @ self.MstackT).toarray()                      # Y[:, j] = M^(j) x_N
        dMx = Y @ self.Bmat
        T = sp.kron(sp.eye(K0, format='csr'), sp.csr_matrix(c[:, None]), format='csr') + \
            sp.kron(sp.csr_matrix(c[:, None]), sp.eye(K0, format='csr'), format='csr')
        dbda = (self.Z @ T) @ self.Bmat if sp.issparse(self.Z @ T) is False else ((self.Z @ T).toarray() @ self.Bmat)
        V = dMx - dbda
        Ja = V - Ur @ (Ur.T @ V)
        Ju = (Ja - np.outer(Ja @ a, a)) @ self.P / na
        self._nfev += 1
        return r, Ju

    def search_lm(self, n_restarts=10, seed=0, max_nfev=200, verbose=False, stop_rel=1e-13, init=None):
        """Random-restart Levenberg-Marquardt on the projected residual.  Same output format as search()."""
        from scipy.optimize import least_squares
        rng = np.random.default_rng(seed)
        out = []
        t0 = time.time()
        for it in range(n_restarts):
            if init is not None and it == 0:
                u0 = self.P.T @ np.asarray(init, float)
            else:
                u0 = rng.standard_normal(self.dimP)
            u0 /= np.linalg.norm(u0)
            cache = {}

            def fun(u):
                key = u.tobytes()
                if key not in cache:
                    cache.clear(); cache[key] = self.residual_and_jac(u)
                return cache[key][0]

            def jac(u):
                key = u.tobytes()
                if key not in cache:
                    cache.clear(); cache[key] = self.residual_and_jac(u)
                return cache[key][1]
            try:
                res = least_squares(fun, u0, jac=jac, method='lm', xtol=1e-15, ftol=1e-15, gtol=1e-15, max_nfev=max_nfev)
                uu = res.x; nit = int(res.nfev)
            except Exception as ex:  # pragma: no cover
                uu = u0; nit = -1
            a = self.P @ uu; a /= np.linalg.norm(a)
            f, x, r = self.value(a)
            bn = self.bnorm(a)
            rel = f / max(bn * bn, 1e-300)
            spur, srel = self.is_spurious(a)
            out.append({'value': f, 'rel': rel, 'a': a, 'spurious': spur, 'div_rel': srel, 'iters': nit, 'restart': it})
            if verbose:
                print(f'[sectorvarpro-lm] restart {it}: rel={rel:.3e} nfev={nit} spurious={spur} ({time.time()-t0:.1f}s)', file=sys.stderr)
            if rel < stop_rel and not spur:
                break
        out.sort(key=lambda c_: (c_['spurious'], c_['rel']))
        return out

    def polish_lm(self, a, max_nfev=400):
        res = self.search_lm(n_restarts=1, init=a, max_nfev=max_nfev)
        return res[0]['a'], res[0]['rel']

    def polish(self, a, maxiter=3000, gtol=1e-16):
        from scipy.optimize import minimize
        u0 = self.P.T @ np.asarray(a, float)
        u0 /= max(np.linalg.norm(u0), 1e-300)
        res = minimize(self.value_and_grad, u0, jac=True, method='L-BFGS-B',
                       options={'maxiter': maxiter, 'gtol': gtol, 'ftol': 1e-18, 'maxcor': 30})
        a1 = self.P @ res.x; a1 /= np.linalg.norm(a1)
        return a1, self.rel(a1)

    def grid_scan(self, npts=720):
        out = []
        if self.dimP == 1:
            a = self.P[:, 0]
            out.append((self.rel(a), a))
        elif self.dimP == 2:
            for t in np.linspace(0, np.pi, npts, endpoint=False):
                a = self.P @ np.array([np.cos(t), np.sin(t)])
                out.append((self.rel(a), a))
        out.sort(key=lambda z: z[0])
        return out

    def D_float(self, a):
        c = self.coeffs(np.asarray(a, float))
        return {m: float(c[j]) for j, m in enumerate(self.Dm) if abs(c[j]) > 1e-15}

    def coords_of(self, Dpoly):
        """Family coordinates of a poly (least squares) and the relative residual of the projection."""
        c = np.zeros(self.K0)
        didx = {m: j for j, m in enumerate(self.Dm)}
        extra = 0.0
        for e, v in Dpoly.items():
            if e in didx:
                c[didx[e]] = float(v)
            else:
                extra += float(v) ** 2
        x, *_ = sla.lstsq(self.Bmat, c)
        res = np.linalg.norm(self.Bmat @ x - c) ** 2 + extra
        return x, float(math.sqrt(res) / max(np.linalg.norm(c), 1e-300))


class HessRelax:
    """Hessian relaxation on the w-space: D = sum_k a_k m_k F_{i_k}, N = A w (w_k = m_k e_{i_k}), no Koszul correction.
    E2 then reads  D div(A w) - (A w)(D) = F Q  (deg Q = 2d-6).  Residual r(a) = V(a,a) - MQ x, f(a) = min_x |r|^2.
    A zero of f gives a genuine certificate with N = A w (no E1 unknowns needed); failure excludes nothing."""

    def __init__(self, inst, d, lab, verbose=False):
        t0 = time.time()
        F, A, q = inst.F, inst.A, inst.q
        assert q == 1
        self.inst, self.d, self.lab = inst, d, lab
        items = []  # (i, m)
        for i in range(NV):
            ml = inst.sublab(lab, inst.labFi[i])
            for m in monomials(d - 5):
                if inst.label(m) == ml:
                    items.append((i, m))
        self.items = items
        K = len(items); self.K = K
        if K == 0:
            self.dimP = 0; return
        Dk = [shift(inst.Fi[i], m, 1) for i, m in items]
        self.Dk = Dk
        Am = [mul(A, {m: Fraction(1)}) for i, m in items]
        rows = {}

        def ridx(e):
            if e not in rows:
                rows[e] = len(rows)
            return rows[e]
        # v_kl = D_k * d_{i_l}(A m_l) - A m_l * d_{i_l}(D_k)
        pair = {}
        for k in range(K):
            for l in range(K):
                il = items[l][0]
                v = sub(mul(Dk[k], pderiv(Am[l], il)), mul(Am[l], pderiv(Dk[k], il)))
                pair[(k, l)] = v
                for e in v:
                    ridx(e)
        labQ = inst.addlab(inst.labA, lab, lab)
        degQ = 2 * d - 6
        Qm = [m for m in monomials(degQ) if inst.label(m) == labQ] if degQ >= 0 else []
        FQ = [shift(F, m, 1) for m in Qm]
        for P in FQ:
            for e in P:
                ridx(e)
        R = len(rows); self.rows = R
        MQ = np.zeros((R, len(Qm)))
        for j, P in enumerate(FQ):
            for e, v in P.items():
                MQ[rows[e], j] = float(v)
        # orthonormal basis of col(MQ): projector
        if len(Qm):
            U, s, _ = np.linalg.svd(MQ, full_matrices=False)
            r = int(np.sum(s > 1e-10 * s[0]))
            self.QQ = U[:, :r]
        else:
            self.QQ = np.zeros((R, 0))
        self.nQ = len(Qm)
        # symmetrized pair tensors: W_k = (R x K), column l = v_kl + v_lk
        self.Wk = []
        for k in range(K):
            ri, ci, vals = [], [], []
            for l in range(K):
                v = add(pair[(k, l)], pair[(l, k)])
                for e, c in v.items():
                    ri.append(rows[e]); ci.append(l); vals.append(float(c))
            self.Wk.append(sp.csr_matrix((np.array(vals), (np.array(ri, dtype=np.int64), np.array(ci, dtype=np.int64))), shape=(R, K)))
        # exclude F-multiples: D(a) in F S_{d-6}: solve [Dk | F m] nullspace
        self.P = np.eye(K); self.excluded_dim = 0
        if d >= 6:
            Gm = inst.sector_monomials(d - 6, lab)
            Fcols = [shift(F, m, 1) for m in Gm]
            Mb, _ = _dense(Dk + [scale(C, -1) for C in Fcols])
            ns = sla.null_space(Mb)
            S = ns[:K, :] if ns.size else np.zeros((K, 0))
            if S.shape[1]:
                U, s, _ = np.linalg.svd(S, full_matrices=True)
                r = int(np.sum(s > 1e-10 * max(1.0, s[0])))
                self.P, self.excluded_dim = U[:, r:], r
        self.dimP = self.P.shape[1]
        self.build_time = time.time() - t0
        if verbose:
            print(f'[hessrelax] d={d} lab={lab} K={K} dimP={self.dimP} rows={R} nQ={self.nQ} built {self.build_time:.1f}s', file=sys.stderr)

    def _Vaa(self, a):
        # V(a,a) = 1/2 sum_k a_k (W_k a)
        v = np.zeros(self.rows)
        for k in range(self.K):
            if a[k]:
                v += a[k] * (self.Wk[k] @ a)
        return 0.5 * v

    def value(self, a):
        a = np.asarray(a, float); a = a / np.linalg.norm(a)
        v = self._Vaa(a)
        r = v - self.QQ @ (self.QQ.T @ v)
        return float(r @ r), float(v @ v)

    def value_and_grad(self, u):
        a_full = self.P @ u
        na = np.linalg.norm(a_full); a = a_full / na
        v = self._Vaa(a)
        r = v - self.QQ @ (self.QQ.T @ v)
        f = float(r @ r)
        # d v / d a_k = W_k a  (symmetrized)  -> grad_k = 2 r . (W_k a)
        g = np.array([2.0 * float(r @ (self.Wk[k] @ a)) for k in range(self.K)])
        g_full = (g - float(g @ a) * a) / na
        return f, self.P.T @ g_full

    def search(self, n_restarts=100, seed=0, maxiter=500):
        from scipy.optimize import minimize
        rng = np.random.default_rng(seed)
        out = []
        for it in range(n_restarts):
            u0 = rng.standard_normal(self.dimP); u0 /= np.linalg.norm(u0)
            res = minimize(self.value_and_grad, u0, jac=True, method='L-BFGS-B',
                           options={'maxiter': maxiter, 'gtol': 1e-12, 'ftol': 1e-16})
            a = self.P @ res.x; a /= np.linalg.norm(a)
            f, vv = self.value(a)
            out.append({'value': f, 'rel': f / max(vv, 1e-300), 'a': a, 'iters': int(res.nit), 'restart': it})
        out.sort(key=lambda c: c['rel'])
        return out

    def D_float(self, a):
        D = {}
        for k, B in enumerate(self.Dk):
            if a[k] == 0:
                continue
            for e, v in B.items():
                D[e] = D.get(e, 0.0) + a[k] * float(v)
        return {e: v for e, v in D.items() if abs(v) > 1e-15}


