def label_of_poly(inst, P):
    labs = {inst.label(m) for m in P}
    if len(labs) != 1:
        return None
    return labs.pop()


class Instance:
    def __init__(self, iid=IID):
        self.iid = iid
        self.F, self.A, self.q, self.rec = core.load_instance(iid)
        self.G = symmetry.diagonal_group(self.F)
        self.n = self.G.order
        els = set(self.G.elements)
        if iid == IID:
            gens = [(5, 5, 0, 5, 5, 0), (0, 0, 3, 0, 0, 0), (0, 0, 0, 3, 3, 0)]
            assert all(g in els for g in gens), 'sector generators not in the group'
        else:
            gens = [tuple(g) for g in self.G.generators]
        self.gens = gens
        self.Fi = [pderiv(self.F, i) for i in range(NV)]
        self.labF = label_of_poly(self, self.F)
        self.labA = label_of_poly(self, self.A)
        self.labFi = [label_of_poly(self, Fi) for Fi in self.Fi]
        assert self.labF is not None and self.labA is not None

    def label(self, m):
        n = self.n
        return tuple(sum(a * b for a, b in zip(m, g)) % n for g in self.gens)

    def addlab(self, *labs):
        return tuple(sum(v) % self.n for v in zip(*labs))

    def sublab(self, l1, l2):
        return tuple((a - b) % self.n for a, b in zip(l1, l2))

    def sector_monomials(self, deg, lab):
        return [m for m in monomials(deg) if self.label(m) == lab]

    def labels_in_degree(self, deg):
        out = {}
        for m in monomials(deg):
            out.setdefault(self.label(m), 0)
            out[self.label(m)] += 1
        return out

    def jac_generators_sector(self, deg, lab, p=None):
        """m*F_i of degree deg with label lab (exact or mod p)."""
        gens = []
        if deg < 5:
            return gens
        for i in range(NV):
            Fi = self.Fi[i] if p is None else reduce_mod(self.Fi[i], p)
            if not Fi:
                continue
            ml = self.sublab(lab, self.labFi[i])
            for m in monomials(deg - 5):
                if self.label(m) == ml:
                    gens.append(shift(Fi, m, 1, p))
        return gens


def _dense(polys, rows=None):
    """Dense float matrix (rows x len(polys)); rows dict is extended in place."""
    rows = {} if rows is None else rows
    for P in polys:
        for e in P:
            rows.setdefault(e, len(rows))
    M = np.zeros((len(rows), len(polys)))
    for j, P in enumerate(polys):
        for e, v in P.items():
            M[rows[e], j] = float(v)
    return M, rows


def _orthonormal_polys(polys, tol=1e-10):
    """Orthonormal basis (list of float polys) of span(polys) in monomial coordinates; returns (basis, coeff matrix C) with
    basis_j = sum_i C[i,j] polys_i."""
    M, rows = _dense(polys)
    U, s, Vt = np.linalg.svd(M, full_matrices=False)
    r = int(np.sum(s > tol * max(s[0], 1e-300))) if s.size else 0
    inv = {i: e for e, i in rows.items()}
    basis = []
    for j in range(r):
        col = U[:, j]
        basis.append({inv[i]: float(col[i]) for i in range(len(col)) if abs(col[i]) > 1e-14})
    # coefficients: U[:, :r] = M @ (V_r / s_r)  ->  C = Vt[:r].T / s[:r]
    C = (Vt[:r].T / s[:r]) if r else np.zeros((len(polys), 0))
    return basis, C


def e1_family(inst, d, lab, V=None, tol=1e-8, verbose=False):
    """Orthonormal float basis of {D in V : A*D in J(F)}, V = sector-lab monomials of degree d (default) or span(V).

    Returns dict(basis, K, K0, rows, ngens, rank_gens, sv_kept_max, sv_dropped_min) or None if V is empty."""
    t0 = time.time()
    if V is None:
        Vp = [{m: 1.0} for m in inst.sector_monomials(d, lab)]
    else:
        Vp = [dict(P) for P in V if P]
        for P in Vp:
            assert label_of_poly(inst, P) == lab, 'subspace generator outside the sector'
        Vp, _ = _orthonormal_polys(Vp)
    if not Vp:
        return None
    K0 = len(Vp)
    tl = inst.addlab(inst.labA, lab)
    gens = inst.jac_generators_sector(d + 6, tl)
    AV = [mul(inst.A, P) for P in Vp]
    rows = {}
    Ma, rows = _dense(AV, rows)
    if gens:
        Mg, rows = _dense(gens, rows)
        # pad Ma to the full row count
        if Ma.shape[0] < len(rows):
            Ma = np.vstack([Ma, np.zeros((len(rows) - Ma.shape[0], K0))])
        U, s, _ = np.linalg.svd(Mg, full_matrices=False)
        rg = int(np.sum(s > 1e-10 * s[0]))
        Qg = U[:, :rg]
        Res = Ma - Qg @ (Qg.T @ Ma)
    else:
        rg = 0
        Res = Ma
    scale_ = max(np.linalg.norm(Ma, axis=0).max(), 1e-300)
    U2, s2, Vt2 = np.linalg.svd(Res, full_matrices=True)
    s2full = np.concatenate([s2, np.zeros(K0 - len(s2))]) if len(s2) < K0 else s2
    keep = [i for i in range(K0) if s2full[i] < tol * scale_]
    sv_dropped_min = float(min([s2full[i] for i in range(K0) if i not in set(keep)], default=float('nan')))
    sv_kept_max = float(max([s2full[i] for i in keep], default=float('nan')))
    basis = []
    for i in keep:
        c = Vt2[i]
        D = {}
        for j in range(K0):
            if abs(c[j]) > 1e-15:
                for e, v in Vp[j].items():
                    D[e] = D.get(e, 0.0) + c[j] * float(v)
        D = {e: v for e, v in D.items() if abs(v) > 1e-14}
        basis.append(D)
    out = {'basis': basis, 'K': len(basis), 'K0': K0, 'rows': len(rows), 'ngens': len(gens), 'rank_gens': rg,
           'sv_kept_max': sv_kept_max, 'sv_dropped_min': sv_dropped_min, 'seconds': round(time.time() - t0, 2)}
    if verbose:
        print(f"[e1_family] d={d} lab={lab} K0={K0} gens={len(gens)} rank={rg} rows={len(rows)} -> K={len(basis)} "
              f"(sv kept<= {sv_kept_max:.1e}, dropped>= {sv_dropped_min:.1e}) {out['seconds']}s", file=sys.stderr)
    return out


def _nmod_from_polys(polys, p, rows=None):
    rows = {} if rows is None else rows
    for P in polys:
        for e in P:
            rows.setdefault(e, len(rows))
    R, C = len(rows), len(polys)
    flat = [0] * (R * C)
    for j, P in enumerate(polys):
        for e, v in P.items():
            flat[rows[e] * C + j] = int(v) % p
    return nmod_mat(R, C, flat, p), rows


def e1_family_dim_modp(inst, d, lab, p=None, V=None):
    """dim {D in V : A D in J(F)} mod p; V = sector monomials by default (V polys must have rational coefficients)."""
    p = p or core.PRIMES[0]
    if V is None:
        Vp = [{m: 1} for m in inst.sector_monomials(d, lab)]
    else:
        Vp = [reduce_mod(P, p) for P in V if P]
    K0 = len(Vp)
    if not K0:
        return {'K0': 0, 'dim': 0, 'rank_gens': 0, 'rank_aug': 0, 'rows': 0}
    tl = inst.addlab(inst.labA, lab)
    gens = inst.jac_generators_sector(d + 6, tl, p)
    Ap = reduce_mod(inst.A, p)
    AV = [mul(Ap, P, p) for P in Vp]
    rows = {}
    if gens:
        Mg, rows = _nmod_from_polys(gens, p, rows)
        rg = Mg.rank()
    else:
        rg = 0
    Maug, rows = _nmod_from_polys(AV + gens, p, dict(rows))
    ra = Maug.rank()
    # dimension of V-part of the kernel of [AV | gens] = K0 - (ra - rg) ... but V may be dependent mod p; assume independent
    MV, _ = _nmod_from_polys(Vp, p)
    rV = MV.rank()
    return {'K0': K0, 'rankV': rV, 'dim': rV - (ra - rg), 'rank_gens': rg, 'rank_aug': ra, 'rows': len(rows), 'p': p}


def jacobian_dim_sector(inst, d, lab, p=None):
    p = p or core.PRIMES[0]
    gens = inst.jac_generators_sector(d, lab, p)
    if not gens:
        return 0
    M, _ = _nmod_from_polys(gens, p)
    return M.rank()


def fmult_dim_sector(inst, d, lab):
    """dim of F * S_{d-6} inside the sector (F has trivial character)."""
    if d < 6:
        return 0
    return len(inst.sector_monomials(d - 6, lab))


