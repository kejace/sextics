# ----------------------------------------------------------------------------- polynomials
def monos(deg):
    """All exponent tuples of total degree deg in 6 variables (deterministic order)."""
    out = []
    for c in itertools.combinations_with_replacement(range(NV), deg):
        e = [0] * NV
        for i in c:
            e[i] += 1
        out.append(tuple(e))
    return out

def pint(P):
    """dict poly with Fraction/int coefficients -> dict with python ints (must be integral)."""
    out = {}
    for e, c in P.items():
        c = Fraction(c)
        assert c.denominator == 1, 'non-integral coefficient'
        if c.numerator:
            out[tuple(e)] = int(c.numerator)
    return out

def padd(P, Q, s=1):
    out = dict(P)
    for e, c in Q.items():
        v = out.get(e, 0) + s * c
        if v:
            out[e] = v
        else:
            out.pop(e, None)
    return out

def pscale(P, s):
    return {e: c * s for e, c in P.items() if c * s}

def pmul(P, Q):
    out = {}
    for e1, c1 in P.items():
        for e2, c2 in Q.items():
            e = tuple(a + b for a, b in zip(e1, e2))
            v = out.get(e, 0) + c1 * c2
            if v:
                out[e] = v
            else:
                out.pop(e, None)
    return out

def pderiv(P, i):
    out = {}
    for e, c in P.items():
        if e[i]:
            e2 = list(e); e2[i] -= 1
            out[tuple(e2)] = c * e[i]
    return out

def pshift(P, m, s=1):
    """P * s * x^m"""
    return {tuple(a + b for a, b in zip(e, m)): c * s for e, c in P.items()}

def ppow(P, k):
    out = {(0,) * NV: 1}
    for _ in range(k):
        out = pmul(out, P)
    return out

def pdeg(P):
    ds = {sum(e) for e in P}
    assert len(ds) <= 1, 'not homogeneous'
    return ds.pop() if ds else -1

def pmod(P, p):
    return {e: c % p for e, c in P.items() if c % p}

def ypar(P):
    """Y-parity of a pure-parity polynomial (0 even, 1 odd); None if mixed."""
    s = {(e[3] + e[4] + e[5]) % 2 for e in P}
    return s.pop() if len(s) == 1 else None

def to_str(P):
    return core.to_str({e: Fraction(c) for e, c in P.items()})

def parse(s):
    return pint(core.parse(s))

def pstr_hash(P):
    return hashlib.sha256(to_str(P).encode()).hexdigest()[:16]

# ----------------------------------------------------------------------------- diagonal group
def diagonal_group(F):
    """All w in (Z/6)^6 such that every monomial of F has the same weight sum(e_i w_i) mod 6.
    Includes the scalars (k,...,k).  Returns int array (n x 6)."""
    exps = np.array(list(F.keys()), dtype=np.int64)
    allw = np.array(list(itertools.product(range(6), repeat=NV)), dtype=np.int64)
    wts = (exps @ allw.T) % 6
    ok = np.all(wts == wts[0:1, :], axis=0)
    return allw[ok]

def subgroup_span(gens):
    """All elements of (Z/6)^6 generated by gens."""
    elems = {(0,) * NV}
    frontier = [(0,) * NV]
    gens = [tuple(int(x) for x in g) for g in gens]
    while frontier:
        new = []
        for e in frontier:
            for g in gens:
                h = tuple((a + b) % 6 for a, b in zip(e, g))
                if h not in elems:
                    elems.add(h); new.append(h)
        frontier = new
    return elems

def generators(Gw):
    """Greedy generating set of the subgroup Gw (rows)."""
    gens = []
    span = {(0,) * NV}
    for w in Gw:
        t = tuple(int(x) for x in w)
        if t not in span:
            gens.append(t)
            span = subgroup_span(gens)
            if len(span) == len(Gw):
                break
    assert len(span) == len(Gw)
    return np.array(gens, dtype=np.int64)

def stabilizer(Gw, D):
    exps = np.array(list(D.keys()), dtype=np.int64)
    wts = (exps @ Gw.T) % 6
    ok = np.all(wts == wts[0:1, :], axis=0)
    return Gw[ok]

def key_of_exps(exps, gens):
    """character key (tuple of weights on generators) of monomials; exps: (k x 6)."""
    return (np.asarray(exps, dtype=np.int64) @ gens.T) % 6

def key_of_poly(P, gens):
    ks = key_of_exps(np.array(list(P.keys()), dtype=np.int64), gens)
    assert np.all(ks == ks[0:1, :]), 'P is not semi-invariant under the generators'
    return tuple(int(x) for x in ks[0])

def key_add(*keys):
    return tuple(sum(x) % 6 for x in zip(*keys))

def key_neg(k):
    return tuple((-x) % 6 for x in k)

def key_mul(k, s):
    return tuple((x * s) % 6 for x in k)

def sector_monos(deg, gens, key):
    """monomials of degree deg whose character key equals `key`."""
    allm = monos(deg)
    if not allm:
        return []
    ks = key_of_exps(np.array(allm, dtype=np.int64), gens)
    sel = np.all(ks == np.array(key, dtype=np.int64)[None, :], axis=1)
    return [allm[i] for i in np.nonzero(sel)[0]]

# ----------------------------------------------------------------------------- Jacobian sectors
class JacobianSectors:
    """Sector-wise linear algebra modulo J(F) = (F2_0..F2_5), mod p, under the FULL diagonal
    group of F (so only semi-invariant polynomials are handled; general polynomials are handled
    componentwise since J is graded by the group)."""
    def __init__(self, F2, p):
        self.F2 = F2; self.p = p
        self.Gw = diagonal_group(F2)
        self.gens = generators(self.Gw)
        self.kF = key_of_poly(F2, self.gens)
        self.kx = [key_of_poly({tuple(int(j == i) for j in range(NV)): 1}, self.gens) for i in range(NV)]
        self.Fi = [pderiv(F2, i) for i in range(NV)]
        self._cache = {}

    def jgens(self, deg, key):
        """integer polys m*F2_i of degree deg and character key."""
        out = []
        for i in range(NV):
            if deg - 5 < 0:
                continue
            need = key_add(key, key_neg(self.kF), self.kx[i])
            for m in sector_monos(deg - 5, self.gens, need):
                out.append(pshift(self.Fi[i], m))
        return out

    def reducer(self, deg, key):
        """(monomial list, index, RREF rows of J-generators (nmod_mat), pivot cols, standard cols).
        cached."""
        ck = (deg, key)
        if ck in self._cache:
            return self._cache[ck]
        ms = sector_monos(deg, self.gens, key)
        idx = {m: i for i, m in enumerate(ms)}
        gens = self.jgens(deg, key)
        n = len(ms)
        if gens:
            rows = []
            for g in gens:
                r = [0] * n
                for e, c in g.items():
                    r[idx[e]] = c % self.p
                rows.extend(r)
            M = nmod_mat(len(gens), n, rows, self.p)
            R, rk = M.rref()
            piv = []
            for i in range(rk):
                for j in range(n):
                    if int(R[i, j]) != 0:
                        piv.append(j); break
            Rrows = R  # (len(gens) x n), first rk rows meaningful
        else:
            rk = 0; piv = []; Rrows = None
        std = [j for j in range(n) if j not in set(piv)]
        res = dict(monos=ms, idx=idx, R=Rrows, rank=rk, piv=piv, std=std, ngens=len(gens))
        self._cache[ck] = res
        return res

    def vec(self, P, red):
        v = [0] * len(red['monos'])
        for e, c in P.items():
            v[red['idx'][e]] = c % self.p
        return v

    def normal_form_coords(self, polys, deg, key):
        """coordinates (in the standard-monomial basis of (S/J)_deg^key) of the classes of polys.
        Returns nmod_mat (len(polys) x #std)."""
        red = self.reducer(deg, key)
        n = len(red['monos'])
        V = nmod_mat(len(polys), n, [x for P in polys for x in self.vec(P, red)], self.p)
        if red['rank']:
            rk = red['rank']; piv = red['piv']
            Rk = nmod_mat(rk, n, [int(red['R'][i, j]) for i in range(rk) for j in range(n)], self.p)
            # V_red = V - V[:, piv] @ Rk
            Vp = nmod_mat(len(polys), rk, [int(V[i, j]) for i in range(len(polys)) for j in piv], self.p)
            V = V - Vp * Rk
        std = red['std']
        return nmod_mat(len(polys), len(std), [int(V[i, j]) for i in range(len(polys)) for j in std], self.p)

    def ring_dim(self, deg, key):
        red = self.reducer(deg, key)
        return len(red['std'])

    def e1_kernel(self, A, d, key):
        """{D in (S_d)_key : A D in J}.  Returns dict(dim, basis (list of int polys mod p),
        kernel_dim (= dim incl. J_d part), jdim (dim J_d^key), ring_dim)."""
        kA = key_of_poly(A, self.gens)
        ms = sector_monos(d, self.gens, key)
        if not ms:
            return dict(dim=0, basis=[], kernel_dim=0, jdim=0, ring_dim=0, nmonos=0)
        tgt = key_add(key, kA)
        red = self.reducer(d + pdeg(A), tgt)
        AM = [pmul(A, {m: 1}) for m in ms]
        C = self.normal_form_coords(AM, d + pdeg(A), tgt)   # (#ms x #std)
        # kernel of C^T? we need {c : sum c_m [A m] = 0} = left nullspace of C
        X, nul = C.transpose().nullspace()
        basis = []
        for j in range(nul):
            Dp = {}
            for i, m in enumerate(ms):
                v = int(X[i, j])
                if v:
                    Dp[m] = v
            basis.append(Dp)
        jd = self.reducer(d, key)['rank']
        return dict(dim=nul - jd, basis=basis, kernel_dim=nul, jdim=jd, ring_dim=len(ms) - jd, nmonos=len(ms))

