def all_sector_keys(gens, deg):
    ks = key_of_exps(np.array(monos(deg), dtype=np.int64), gens)
    return sorted({tuple(int(x) for x in k) for k in ks})

class FixedDSystem:
    """Character-restricted linear system for fixed D (integer coefficients).
    H = subgroup of the diagonal group stabilizing D (default: full stabilizer)."""
    def __init__(self, F2, A, q, D, H=None, verbose=False, ell=2):
        self.F2, self.A, self.q, self.D, self.ell = F2, A, q, D, ell
        self.d = pdeg(D); self.dN = self.d + 6 * q - 5; self.dQ = 2 * self.d - 6; self.dE = 2 * self.d + 6 * q
        Gw = diagonal_group(F2)
        if H is None:
            H = stabilizer(Gw, D)
        self.H = H
        self.Hsize = len(H)
        gens = generators(H) if len(H) > 1 else np.zeros((0, NV), dtype=np.int64)
        self.gens = gens
        if len(gens):
            kA = key_of_poly(A, gens); kD = key_of_poly(D, gens); kF = key_of_poly(F2, gens)
            kx = [key_of_poly({tuple(int(j == i) for j in range(NV)): 1}, gens) for i in range(NV)]
            kN = [key_add(kA, kD, key_neg(kF), kx[i]) for i in range(NV)]
            kQ = key_add(kA, key_mul(kD, 2), key_mul(key_neg(kF), q + 1))
            kE = key_add(kA, key_mul(kD, 2))
            self.Nmonos = [sector_monos(self.dN, gens, kN[i]) for i in range(NV)]
            self.Qmonos = sector_monos(self.dQ, gens, kQ) if self.dQ >= 0 else []
            self.Emonos = sector_monos(self.dE, gens, kE)
        else:
            self.Nmonos = [monos(self.dN) for i in range(NV)]
            self.Qmonos = monos(self.dQ) if self.dQ >= 0 else []
            self.Emonos = monos(self.dE)
        self.cols = [('N', i, m) for i in range(NV) for m in self.Nmonos[i]] + [('Q', 0, m) for m in self.Qmonos]
        self.ncols = len(self.cols); self.nrows = len(self.Emonos)
        self.ridx = {m: i for i, m in enumerate(self.Emonos)}
        # column polynomials
        Fi = [pderiv(F2, i) for i in range(NV)]
        Di = [pderiv(D, i) for i in range(NV)]
        c1 = -q * ell ** q; c2 = ell ** q
        P = [pscale(pmul(D, Fi[i]), c1) for i in range(NV)]          # * N_i
        T = pscale(pmul(F2, D), c2)                                   # * d_i N_i
        Rr = [pscale(pmul(F2, Di[i]), c2) for i in range(NV)]         # * (-N_i)
        FQ = pscale(ppow(F2, q + 1), -1)
        self.colpolys = []
        for (kind, i, m) in self.cols:
            if kind == 'N':
                col = pshift(P[i], m)
                col = padd(col, pshift(Rr[i], m), -1)
                if m[i] > 0:
                    m2 = list(m); m2[i] -= 1
                    col = padd(col, pshift(T, tuple(m2), m[i]))
            else:
                col = pshift(FQ, m)
            self.colpolys.append(col)
        self.b = pscale(pmul(A, pmul(D, D)), -(ell ** (q + 1)))
        # sanity: every monomial lies in the row sector
        for col in self.colpolys:
            for e in col:
                assert e in self.ridx, 'column monomial outside row sector'
        for e in self.b:
            assert e in self.ridx, 'rhs monomial outside row sector'
        self.verbose = verbose

    def int_matrix(self):
        """numpy object/int64 matrix (rows x cols) and rhs vector (ints)."""
        M = np.zeros((self.nrows, self.ncols), dtype=object)
        for j, col in enumerate(self.colpolys):
            for e, c in col.items():
                M[self.ridx[e], j] = c
        b = np.zeros(self.nrows, dtype=object)
        for e, c in self.b.items():
            b[self.ridx[e]] = c
        return M, b

    def aug_mod(self, p, M=None, b=None):
        if M is None:
            M, b = self.int_matrix()
        flat = []
        for i in range(self.nrows):
            row = M[i]
            flat.extend(int(x) % p for x in row)
            flat.append(int(b[i]) % p)
        return nmod_mat(self.nrows, self.ncols + 1, flat, p)

    def evaluate(self, N, Q):
        """direct polynomial evaluation of 2^(q+1) E for given N (list of 6 int polys), Q."""
        q = self.q; F2 = self.F2; D = self.D; A = self.A; ell = self.ell
        E = pscale(pmul(A, pmul(D, D)), ell ** (q + 1))
        Fi = [pderiv(F2, i) for i in range(NV)]
        for i in range(NV):
            E = padd(E, pscale(pmul(D, pmul(N[i], Fi[i])), -q * ell ** q))
            E = padd(E, pscale(pmul(F2, padd(pmul(D, pderiv(N[i], i)), pmul(N[i], pderiv(D, i)), -1)), ell ** q))
        E = padd(E, pmul(ppow(F2, q + 1), Q), -1)
        return E

def pivots_of_rref(R, rk, ncols):
    piv = []
    for i in range(rk):
        for j in range(ncols):
            if int(R[i, j]) != 0:
                piv.append(j); break
    return piv

def analyze_mod_p(sysm, p, M=None, b=None):
    """rank data mod p.  Returns dict(rank, rank_aug, consistent, pivots)."""
    Aug = sysm.aug_mod(p, M, b)
    R, rk = Aug.rref()
    piv = pivots_of_rref(R, rk, sysm.ncols + 1)
    cons = (sysm.ncols not in piv)
    return dict(p=p, rank_aug=rk, rank=rk - (0 if cons else 1), consistent=cons, pivots=piv, nullity=sysm.ncols - (rk - (0 if cons else 1)))

def farkas_certificate(sysm, p, M, b, pivots):
    """Exact Farkas certificate of inconsistency over Q from a mod-p pivot structure.
    Returns dict(rows=R (row indices), Y=[ints], ell=int, verified=bool, seconds)."""
    t0 = time.time()
    C = list(pivots)                       # column basis of [M|b] mod p (includes b = last col)
    assert sysm.ncols in C
    r1 = len(C)
    # row basis: rref of Aug[:,C]^T
    AugC = np.zeros((sysm.nrows, r1), dtype=object)
    for jj, j in enumerate(C):
        if j < sysm.ncols:
            AugC[:, jj] = M[:, j]
        else:
            AugC[:, jj] = b
    flat = [int(AugC[i, jj]) % p for jj in range(r1) for i in range(sysm.nrows)]
    T = nmod_mat(r1, sysm.nrows, flat, p)
    RT, rkT = T.rref()
    assert rkT == r1, (rkT, r1)
    Rows = pivots_of_rref(RT, rkT, sysm.nrows)
    # square system S^T y = e_b  with S = Aug[Rows, C]
    S = fmpz_mat(r1, r1, [int(AugC[i, jj]) for jj in range(r1) for i in Rows])   # this is S^T
    e = fmpz_mat(r1, 1, [1 if C[jj] == sysm.ncols else 0 for jj in range(r1)])
    y = S.solve(e)                          # fmpq_mat
    # clear denominators
    ys = [Fraction(int(y[i, 0].p), int(y[i, 0].q)) for i in range(r1)]
    ell = 1
    for f in ys:
        ell = ell * f.denominator // math.gcd(ell, f.denominator)
    Y = [int(f * ell) for f in ys]
    # exact verification over the FULL row set R and ALL columns
    Yrow = fmpz_mat(1, r1, Y)
    AugR = fmpz_mat(r1, sysm.ncols + 1, [int(M[i, j]) if j < sysm.ncols else int(b[i]) for i in Rows for j in range(sysm.ncols + 1)])
    prod = Yrow * AugR
    ok = all(int(prod[0, j]) == 0 for j in range(sysm.ncols)) and int(prod[0, sysm.ncols]) == ell and ell != 0
    return dict(rows=Rows, Y=[str(v) for v in Y], ell=str(ell), verified=bool(ok), seconds=round(time.time() - t0, 2), size=r1)

def exact_solution(sysm, p, M, b, pivots):
    """If consistent mod p, try to lift: choose column basis C = pivots (not containing b),
    row basis, solve square system exactly, verify exactly.  Returns (N, Q, ok) or None."""
    C = list(pivots); r = len(C)
    AugC = np.zeros((sysm.nrows, r), dtype=object)
    for jj, j in enumerate(C):
        AugC[:, jj] = M[:, j]
    flat = [int(AugC[i, jj]) % p for jj in range(r) for i in range(sysm.nrows)]
    T = nmod_mat(r, sysm.nrows, flat, p)
    RT, rkT = T.rref()
    Rows = pivots_of_rref(RT, rkT, sysm.nrows)
    S = fmpz_mat(r, r, [int(AugC[i, jj]) for i in Rows for jj in range(r)])
    bb = fmpz_mat(r, 1, [int(b[i]) for i in Rows])
    x = S.solve(bb)
    xs = [Fraction(int(x[i, 0].p), int(x[i, 0].q)) for i in range(r)]
    N = [dict() for _ in range(NV)]; Q = {}
    for jj, j in enumerate(C):
        kind, i, m = sysm.cols[j]
        if xs[jj] == 0:
            continue
        if kind == 'N':
            N[i][m] = xs[jj]
        else:
            Q[m] = xs[jj]
    # exact check with Fractions through the direct evaluation (scale to ints)
    L = 1
    for f in xs:
        L = L * f.denominator // math.gcd(L, f.denominator)
    Ni = [{e: int(c * L) for e, c in Nk.items()} for Nk in N]
    Qi = {e: int(c * L) for e, c in Q.items()}
    E = sysm.evaluate(Ni, Qi)
    # evaluate is linear in (N,Q) except the A D^2 term: scaled check:
    # 2^(q+1) A D^2 * L + (linear part)(L x) must be 0  -> use evaluate with scaled A? simpler: compare
    lin = padd(E, pscale(pmul(sysm.A, pmul(sysm.D, sysm.D)), sysm.ell ** (sysm.q + 1)), -1)   # linear part at Lx
    tot = padd(lin, pscale(pmul(sysm.A, pmul(sysm.D, sysm.D)), sysm.ell ** (sysm.q + 1) * L))
    ok = (len(tot) == 0)
    return dict(N=[{e: Fraction(c, L) for e, c in Nk.items()} for Nk in Ni], Q={e: Fraction(c, L) for e, c in Qi.items()}, ok=ok)

def solve_fixed_D(F2, A, q, D, primes=(P1, P2), farkas=True, lift=True, H=None, verbose=False, ell=2):
    """Full pipeline.  Returns a JSON-able receipt."""
    t0 = time.time()
    sysm = FixedDSystem(F2, A, q, D, H=H, ell=ell)
    M, b = sysm.int_matrix()
    rec = dict(engine=ENGINE_TAG, d=sysm.d, D=to_str(D), D_hash=pstr_hash(D), H=int(sysm.Hsize),
               cols=sysm.ncols, rows=sysm.nrows, primes=[], ranks=[], consistent_modp=[], status=None)
    last = None
    for p in primes:
        an = analyze_mod_p(sysm, p, M, b)
        rec['primes'].append(p); rec['ranks'].append([an['rank'], an['rank_aug']]); rec['consistent_modp'].append(an['consistent'])
        last = an
        if an['consistent']:
            break
    if not last['consistent']:
        rec['status'] = 'inconsistent'
        if farkas:
            fc = farkas_certificate(sysm, last['p'], M, b, last['pivots'])
            rec['farkas'] = dict(size=fc['size'], verified=fc['verified'], seconds=fc['seconds'], ell_digits=len(fc['ell']))
            rec['status'] = 'inconsistent-Q-certified' if fc['verified'] else 'inconsistent-modp-only'
            rec['_farkas_full'] = fc
    else:
        rec['status'] = 'consistent-modp'
        if lift:
            sol = exact_solution(sysm, last['p'], M, b, last['pivots'])
            rec['status'] = 'SOLVED-EXACT' if sol['ok'] else 'consistent-modp-lift-failed'
            rec['_solution'] = sol
    rec['seconds'] = round(time.time() - t0, 2)
    return rec

