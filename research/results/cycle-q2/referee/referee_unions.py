#!/usr/bin/env python3
"""referee_unions.py -- corrected replay of the degree-6 'mixed character' exclusions (lane cycle-q2).

Input: wave2-excl/hess6_p<P>.quadrics.json (426 relaxation quadrics in the 62 coordinates of the mod-p E1 kernel K_6,
grouped into 46 character sectors).  For every union T of s sectors:
  * T without the trivial sector:  dim(std(I_T)) must be 0  (only the origin => no projective point)        [same as subsets6]
  * T containing the trivial sector:  the needed statement is V(I_T) subset of {all nontrivial coordinates = 0}, i.e.
    sat(I_T, m'_T) = (1) with m'_T the IDEAL generated by the nontrivial variables of T.  subsets6.py saturated by the
    PRODUCT of those variables, which only shows that every point has SOME nontrivial coordinate zero; the two tests agree
    only when every nontrivial sector of T is 1-dimensional.  We run the ideal saturation.
I_T lives in the polynomial ring of T's own variables (dropping the other coordinates is the same as setting them to 0).
usage: python3 -I referee_unions.py --size 2 [--prime 1000000007] [--batch 300] [--only-trivial]
"""
import json, subprocess, re, collections, itertools, time, argparse, os, sys
ap = argparse.ArgumentParser(); ap.add_argument('--size', type=int, default=2); ap.add_argument('--prime', type=int, default=1000000007)
ap.add_argument('--batch', type=int, default=300); ap.add_argument('--only-trivial', action='store_true')
a = ap.parse_args(); t0 = time.time()
PK = '/tmp/hodge/results/cycle-q2/wave2-excl'
Q = json.load(open(f'{PK}/hess6_p{a.prime}.quadrics.json'))
keys = [tuple(k) for k in Q['basis_keys']]; p = Q['prime']; assert p == a.prime
bysec = collections.defaultdict(list)
for i, k in enumerate(keys): bysec[k].append(i)
secs = sorted(bysec); triv = (0, 0, 0)
quads = [{tuple(map(int, kk.split(','))): int(v) for kk, v in q['terms'].items()} for q in Q['quadrics']]
subsets = [T for T in itertools.combinations(secs, a.size) if (triv in T or not a.only_trivial)]
out = {'prime': p, 'size': a.size, 'n': len(subsets), 'test': 'dim for nontrivial unions; IDEAL saturation by the nontrivial variables for trivial-containing unions', 'results': []}
ndone = 0
path = f'/tmp/hodge/referee/cycle-q2/scratch_unions_{a.size}_{a.prime}.sing'   # overwritten per batch
for start in range(0, len(subsets), a.batch):
    chunk = subsets[start:start + a.batch]
    lines = ['LIB "elim.lib";']
    for T in chunk:
        sidx = sorted(set().union(*[set(bysec[k]) for k in T]))
        vn = {i: f'c{i+1}' for i in sidx}
        polys = []
        for terms in quads:
            tt = {ab: v for ab, v in terms.items() if ab[0] in vn and ab[1] in vn}
            if tt: polys.append('+'.join(f'{v}*{vn[x]}*{vn[y]}' if x != y else f'{v}*{vn[x]}^2' for (x, y), v in sorted(tt.items())))
        tag = '|'.join(''.join(map(str, k)) for k in T)
        lines.append(f'ring r = {p}, ({",".join(vn[i] for i in sidx)}), dp;')
        lines.append('ideal I = ' + (',\n'.join(polys) if polys else '0') + ';')
        lines.append(f'ideal G = std(I); "RES {tag} DIM", dim(G);')
        if triv in T:
            nontriv = [vn[i] for k in T if k != triv for i in bysec[k]]
            lines.append('ideal mp = ' + ','.join(nontriv) + ';')
            lines.append('def S = sat(I, mp); ideal Sat; if (typeof(S) == "list") { Sat = S[1]; } else { Sat = S; }')
            lines.append(f'"SAT {tag} DIM", dim(std(Sat));')
        lines.append('kill r;')
    lines.append('quit;')
    open(path, 'w').write('\n'.join(lines) + '\n')
    r = subprocess.run(['Singular', '-q', path], capture_output=True, text=True, timeout=6000)
    res = re.findall(r'RES (\S+) DIM (-?\d+)', r.stdout); sat = dict(re.findall(r'SAT (\S+) DIM (-?\d+)', r.stdout))
    assert len(res) == len(chunk), (len(res), len(chunk), r.stderr[-500:])
    for tag, dm in res:
        out['results'].append({'T': tag, 'dim': int(dm), 'sat_dim': int(sat[tag]) if tag in sat else None})
    ndone += len(chunk)
    print(f'{ndone}/{len(subsets)} done [{time.time()-t0:.0f}s]', flush=True)
R = out['results']
nontriv_bad = [x for x in R if x['sat_dim'] is None and x['dim'] != 0]
triv_bad = [x for x in R if x['sat_dim'] is not None and x['sat_dim'] != -1]
out['summary'] = {'n_nontrivial_unions': sum(1 for x in R if x['sat_dim'] is None), 'nontrivial_unions_with_nonempty_variety': nontriv_bad[:50],
                  'n_trivial_containing_unions': sum(1 for x in R if x['sat_dim'] is not None), 'trivial_containing_dims': dict(collections.Counter(x['dim'] for x in R if x['sat_dim'] is not None)),
                  'trivial_containing_unions_NOT_inside_V0': triv_bad[:50], 'n_triv_bad': len(triv_bad), 'n_nontriv_bad': len(nontriv_bad), 'seconds': round(time.time()-t0, 1)}
json.dump(out, open(f'/tmp/hodge/referee/cycle-q2/unions_size{a.size}_p{p}{"_trivonly" if a.only_trivial else ""}.json', 'w'))
print(json.dumps(out['summary'], indent=1))
