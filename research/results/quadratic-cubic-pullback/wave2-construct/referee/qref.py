def monos(deg, nv=6):
    out = []
    for c in itertools.combinations_with_replacement(range(nv), deg):
        e = [0]*nv
        for i in c: e[i] += 1
        out.append(tuple(e))
    return out
def ydeg(e): return e[3]+e[4]+e[5]
def monos_par(deg, par): return [e for e in monos(deg) if ydeg(e) % 2 == par]

def poly_dict(p):
    P = sp.Poly(sp.expand(p), *Z)
    return {tuple(m): sp.Rational(c) for m, c in P.terms()}

def vec(pd, idx, scale=1):
    v = [0]*len(idx)
    for e, c in pd.items():
        v[idx[e]] = c*scale
    return v

def rank_exact(rows):
    """exact rank over Q of a list of rational row vectors (clears denominators row-wise -> fmpz_mat)."""
    if not rows: return 0
    M = []
    for r in rows:
        den = 1
        for c in r:
            den = sp.ilcm(den, sp.Rational(c).q)
        M.append([int(sp.Rational(c)*den) for c in r])
    return fmpz_mat(M).rank()

def rank_modp(rows, p):
    if not rows: return 0
    M = []
    for r in rows:
        M.append([int(sp.Rational(c).p * pow(sp.Rational(c).q, -1, p)) % p for c in r])
    return nmod_mat(M, p).rank()

def hilbert_R(k, par):
    """dim R_k^{par} for R = S/J(F), J generated by six quintics forming a regular sequence,
    bigraded by Y-parity: HS = (1-t^5)^3 (1-u t^5)^3 / ((1-t)^3 (1-u t)^3) with u^2 = 1."""
    # series coefficients as dict (deg, par) -> int, truncated at degree k
    def mul(a, b):
        c = {}
        for (d1, p1), v1 in a.items():
            for (d2, p2), v2 in b.items():
                if d1+d2 <= k:
                    key = (d1+d2, (p1+p2) % 2); c[key] = c.get(key, 0) + v1*v2
        return c
    one = {(0,0): 1}
    geom_even = {(d,0): 1 for d in range(k+1)}             # 1/(1-t)
    geom_odd = {(d, d%2): 1 for d in range(k+1)}             # 1/(1-ut)
    num_even = {(0,0): 1, (5,0): -1}                         # (1-t^5)
    num_odd = {(0,0): 1, (5,1): -1}                          # (1-u t^5)
    s = one
    for _ in range(3): s = mul(s, geom_even)
    for _ in range(3): s = mul(s, geom_odd)
    for _ in range(3): s = mul(s, num_even)
    for _ in range(3): s = mul(s, num_odd)
    return s.get((k, par), 0)

