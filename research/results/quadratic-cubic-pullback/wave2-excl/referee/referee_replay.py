# ---------------------------------------------------------------- part: kernels (E1)
def e1_kernel(d, par, p):
    t0 = time.time()
    tpar = (1 + par) % 2  # A is Y-odd
    cols = monos(d + 6, tpar)
    J = jrows(d + 6, tpar, p)
    Am = monos(d, par)
    Ap = core.reduce_mod(A, p)
    Arows = [core.shift(Ap, m, 1, p) for m in Am]
    MJ = tomat(J, cols, p); rJ = MJ.rank(); del MJ
    M = tomat(J + Arows, cols, p); rM = M.rank(); del M
    dimK = len(Am) - (rM - rJ)
    hJ = dimJ(d + 6, tpar)
    dJd = dimJ(d, par) if d >= 5 else 0
    return dict(check='e1_kernel', d=d, parity=par, prime=p, cols=len(cols), rowsJ=len(J), rowsA=len(Am), rankJ=rJ, hilbJ=hJ,
                J_rank_certified=(rJ == hJ), rank_stack=rM, dimK_modp=dimK, dimJd=dJd, dimK_mod_J_upper=dimK - dJd,
                K_eq_J_rigorous=(rJ == hJ and dimK == dJd), seconds=round(time.time() - t0, 1))


def part_kernels():
    for d in range(0, 8):
        for par in (0, 1):
            log(e1_kernel(d, par, P))


# ---------------------------------------------------------------- part: deg5 (exact two-line argument + modular relaxation)
def part_deg5():
    t0 = time.time()
    # (i) exact: the 21 quartics F_kl are independent (part exact) => w^T Hess(F) w = 0 iff w w^T = 0 iff w = 0.
    # (ii) K_4 = 0 (both parities, certified mod p in part kernels) => A (w^T H w) in J_10 forces both parity parts of
    #      the quartic w^T H w to vanish.  Hence no polar denominator of degree 5 for any w in C^6.
    # Direct replay of the relaxation: kernel of W -> A sum_{k<=l} W_kl F_kl (2 - delta_kl) mod J_10, both parity blocks.
    recs = {}
    for tpar in (0, 1):
        cols = monos(10, tpar)
        J = jrows(10, tpar, P)
        Ap = core.reduce_mod(A, P)
        Wp = []
        keys = [(k, l) for k in range(6) for l in range(k, 6)]
        for (k, l) in keys:
            t = core.mul(Ap, core.reduce_mod(Fij[k][l], P), P)
            if k != l: t = core.scale(t, 2, P)
            tp = {e: v for e, v in t.items() if (e[3] + e[4] + e[5]) % 2 == tpar}
            Wp.append(tp)
        MJ = tomat(J, cols, P); rJ = MJ.rank(); del MJ
        M = tomat(J + Wp, cols, P); rM = M.rank(); del M
        recs[tpar] = dict(cols=len(cols), rankJ=rJ, hilbJ=dimJ(10, tpar), certified=(rJ == dimJ(10, tpar)), rank_stack=rM, added_rank=rM - rJ)
    # the W-kernel of the joint map (both parity blocks) = 21 - rank of the stacked [block0 ; block1] W-part; compute jointly
    cols = monos(10, None)
    J = jrows(10, 0, P) + jrows(10, 1, P)
    Ap = core.reduce_mod(A, P)
    Wp = []
    for (k, l) in [(k, l) for k in range(6) for l in range(k, 6)]:
        t = core.mul(Ap, core.reduce_mod(Fij[k][l], P), P)
        if k != l: t = core.scale(t, 2, P)
        Wp.append(t)
    MJ = tomat(J, cols, P); rJ = MJ.rank(); del MJ
    M = tomat(J + Wp, cols, P); rM = M.rank(); del M
    dimKH = 21 - (rM - rJ)
    log(dict(check='deg5_hessian_relaxation', prime=P, per_parity=recs, joint_cols=len(cols), joint_rankJ=rJ, joint_hilbJ=dimJ(10, 0) + dimJ(10, 1),
             joint_certified=(rJ == dimJ(10, 0) + dimJ(10, 1)), dim_KH_upper=dimKH,
             conclusion=('K_H = 0 (certified upper bound): no polar denominator of degree 5, any parity mixture' if dimKH == 0 and rJ == dimJ(10, 0) + dimJ(10, 1) else 'NOT closed'),
             hand_argument='K_4 = 0 (both parities) + 21 independent second partials => w^T Hess(F) w = 0 => w = 0',
             seconds=round(time.time() - t0, 1)))


# ---------------------------------------------------------------- part: deg6 exact quadric system (all 36 linear coefficients)
def part_deg6():
    t0 = time.time()
    red = {}
    for tp in (0, 1):
        cols = monos(6, tp)
        gens = [core.shift(Fi[i], m, 1) for i in range(6) for m in monos(1, (tp - PARZ[i]) % 2)]
        M = qmat(gens, cols)
        R, rank = M.rref()
        pivots = []
        for i in range(rank):
            j = 0
            while R[i, j] == 0: j += 1
            pivots.append(j)
        rows = [{cols[k]: Fraction(int(R[i, k].p), int(R[i, k].q)) for k in range(len(cols)) if R[i, k] != 0} for i in range(rank)]
        standard = [cols[j] for j in range(len(cols)) if j not in set(pivots)]
        red[tp] = dict(cols=cols, pivots=pivots, rows=rows, standard=standard, rank=rank)
        log(dict(check='J6_exact_rref', parity=tp, exact=True, rank=rank, hilbert_dimJ=dimJ(6, tp), n_standard=len(standard), hilbert_R6=hilbR(6, tp)))

    def nf(T, tp):
        T = dict(T)
        for piv, row in zip(red[tp]['pivots'], red[tp]['rows']):
            m = red[tp]['cols'][piv]
            c = T.get(m, 0)
            if c:
                T = core.sub(T, core.scale(row, c))
        return {e: v for e, v in T.items() if v != 0}

    # unknowns c_a, a = 6 i + k :  w_i = sum_k c_{ik} z_k ;   w^T H w = sum_{a,b} c_a c_b z_k z_l F_ij
    nvar = 36
    pairs = [(a, b) for a in range(nvar) for b in range(a, nvar)]
    quad = {0: {}, 1: {}}   # parity -> {standard monomial -> {pair -> Fraction}}
    for (a, b) in pairs:
        i, k = divmod(a, 6); j, l = divmod(b, 6)
        m = [0] * 6; m[k] += 1; m[l] += 1
        t = core.shift(Fij[i][j], tuple(m), 1)
        if a != b: t = core.scale(t, 2)
        for tp in (0, 1):
            part = {e: v for e, v in t.items() if (e[3] + e[4] + e[5]) % 2 == tp}
            if not part: continue
            r = nf(part, tp)
            for e, v in r.items():
                quad[tp].setdefault(e, {})[(a, b)] = v
    # sanity: the Euler field c_{ii} = 1 must satisfy every quadric (E^T H E = 30 F in J)
    def evalq(qd, c):
        return sum(v * c[a] * c[b] for (a, b), v in qd.items())
    cE = [1 if divmod(a, 6)[0] == divmod(a, 6)[1] else 0 for a in range(nvar)]
    euler_ok = all(evalq(qd, cE) == 0 for tp in (0, 1) for qd in quad[tp].values())
    nq = {tp: len(quad[tp]) for tp in (0, 1)}
    # write Singular over Q: full 36-variable system, slice c35 = 0 (Y2 d/dY2 coefficient), and the two pure-parity sectors
    def qstr(qd):
        den = 1
        for v in qd.values(): den = den * v.denominator // gcd(den, v.denominator)
        terms = []
        for (a, b), v in sorted(qd.items()):
            cst = int(v * den)
            terms.append(f'{cst}*c{a}*c{b}' if a != b else f'{cst}*c{a}^2')
        return '+'.join(terms).replace('+-', '-')
    allq = [qstr(qd) for tp in (0, 1) for qd in quad[tp].values()]
    even_vars = [a for a in range(nvar) if PARZ[divmod(a, 6)[0]] == PARZ[divmod(a, 6)[1]]]
    odd_vars = [a for a in range(nvar) if PARZ[divmod(a, 6)[0]] != PARZ[divmod(a, 6)[1]]]
    sing = os.path.join(HERE, 'referee_deg6_exact.sing')
    with open(sing, 'w') as f:
        f.write('// referee replay: exact degree-6 Hessian relaxation, all 36 linear coefficients c_a (w_i = sum_k c_{6i+k} z_k)\n')
        f.write('ring r = 0, (' + ','.join(f'c{a}' for a in range(nvar)) + '), dp;\n')
        f.write('ideal I = ' + ',\n'.join(allq) + ';\n')
        f.write('ideal G = std(I);\nprint("FULL36 dim " + string(dim(G)));\n')
        f.write('ideal Gs = std(I + ideal(c35));\nprint("SLICE_c35 dim " + string(dim(Gs)));\n')
        # pure-parity sectors: set the other variables to 0
        f.write('ideal Ie = I + ideal(' + ','.join(f'c{a}' for a in odd_vars) + ');\nideal Ge = std(Ie);\nprint("EVEN_SECTOR dim " + string(dim(Ge)));\n')
        f.write('ideal Ges = std(Ie + ideal(c35));\nprint("EVEN_SECTOR_SLICE dim " + string(dim(Ges)));\n')
        f.write('ideal Io = I + ideal(' + ','.join(f'c{a}' for a in even_vars) + ');\nideal Go = std(Io);\nprint("ODD_SECTOR dim " + string(dim(Go)));\n')
        f.write('quit;\n')
    log(dict(check='deg6_exact_quadrics_built', exact=True, n_quadrics=nq, n_vars=nvar, euler_field_satisfies_all=euler_ok,
             even_sector_vars=len(even_vars), odd_sector_vars=len(odd_vars), singular_script=sing,
             transfer_note='condition w^T Hess(F) w in J_6 (both parity parts) is equivalent to A (w^T Hess F w) in J_12 because A.: R_6 -> R_12 is injective (K_6 = J_6, both parities); translation invariance under w -> w + h E (E^T H w = 5 D, E^T H E = 30 F in J) makes the slice c35 = 0 legitimate',
             seconds=round(time.time() - t0, 1)))


