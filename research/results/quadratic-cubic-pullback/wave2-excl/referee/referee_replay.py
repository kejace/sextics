# ---------------------------------------------------------------- own monomials / Hilbert series
def monos(deg, par=None):
    out = []
    for e in itertools.product(range(deg + 1), repeat=5):
        s = sum(e)
        if s <= deg:
            e6 = e + (deg - s,)
            if par is None or (e6[3] + e6[4] + e6[5]) % 2 == par:
                out.append(e6)
    out.sort()
    return out


def hilbR(k, par=None, kmax=24):
    """dim (S/J)_k^{par} for J generated by a regular sequence of 3 Y-even and 3 Y-odd quintics:
    HS = (1-t^5)^3 (1-u t^5)^3 / ((1-t)^3 (1-u t)^3), u^2 = 1; coefficients a + b u."""
    def pmul(x, y): return (x[0] * y[0] + x[1] * y[1], x[0] * y[1] + x[1] * y[0])
    def smul(s1, s2):
        out = [(0, 0)] * (kmax + 1)
        for i, a in enumerate(s1):
            for j, b in enumerate(s2):
                if i + j > kmax: break
                pr = pmul(a, b)
                out[i + j] = (out[i + j][0] + pr[0], out[i + j][1] + pr[1])
        return out
    one = [(1, 0)] + [(0, 0)] * kmax
    def geom(uflag):  # 1/(1 - u^flag t)
        return [((1, 0) if (n % 2 == 0 or not uflag) else (0, 1)) for n in range(kmax + 1)]
    def lin5(uflag):  # 1 - u^flag t^5
        s = [(0, 0)] * (kmax + 1); s[0] = (1, 0); s[5] = (0, -1) if uflag else (-1, 0); return s
    s = one
    for _ in range(3):
        s = smul(s, geom(False)); s = smul(s, geom(True))
    for _ in range(3):
        s = smul(s, lin5(False)); s = smul(s, lin5(True))
    e, o = s[k] if k <= kmax else (0, 0)
    return e + o if par is None else (e if par == 0 else o)


def dimJ(k, par):
    return len(monos(k, par)) - hilbR(k, par)


def tomat(polys, cols, p):
    idx = {e: j for j, e in enumerate(cols)}
    C = len(cols)
    flat = [0] * (len(polys) * C)
    for r, poly in enumerate(polys):
        base = r * C
        for e, v in poly.items():
            flat[base + idx[e]] = v % p
    return nmod_mat(len(polys), C, flat, p)


def jrows(k, tpar, p):
    Fp = core.reduce_mod(F, p)
    Fip = [core.pderiv(Fp, i, p) for i in range(6)]
    rows = []
    for i in range(6):
        for m in monos(k - 5, (tpar - PARZ[i]) % 2):
            rows.append(core.shift(Fip[i], m, 1, p))
    return rows


def qmat(polys, cols):
    idx = {e: j for j, e in enumerate(cols)}
    C = len(cols)
    flat = [fmpq(0)] * (len(polys) * C)
    for r, poly in enumerate(polys):
        for e, v in poly.items():
            flat[r * C + idx[e]] = fmpq(v.numerator, v.denominator)
    return fmpq_mat(len(polys), C, flat)


# ---------------------------------------------------------------- part: exact
def part_exact():
    t0 = time.time()
    S = {}
    for Qi in Qs:
        S = core.add(S, core.mul(Qi, core.mul(Qi, Qi)))
    diff = core.sub(F, S)
    log(dict(check='F_eq_sumQcubed', exact=True, equal=(diff == {}), F_terms=len(F), seconds=round(time.time() - t0, 2)))
    # 21 second partials independent over Q
    sp = [Fij[i][j] for i in range(6) for j in range(i, 6)]
    M = qmat(sp, monos(4))
    log(dict(check='second_partials_rank_exact', exact=True, rank=M.rank(), n=21, note='rank 21 => F is not a join in any coordinates; also used in the degree-5 argument'))
    # delta = det(dQ_i/dZ_j) with own Laplace expansion
    def det(Mx):
        n = len(Mx)
        if n == 1: return Mx[0][0]
        out = {}
        for j in range(n):
            if not Mx[0][j]: continue
            minor = [row[:j] + row[j + 1:] for row in Mx[1:]]
            t = core.mul(Mx[0][j], det(minor))
            out = core.add(out, core.scale(t, -1) if j % 2 else t)
        return out
    delta = det([[core.pderiv(Qs[i], j) for j in range(6)] for i in range(6)])
    cols = monos(6, 1)
    gens = [core.shift(Fi[i], m, 1) for i in range(6) for m in monos(1, (1 - PARZ[i]) % 2)]
    rJ = qmat(gens, cols).rank()
    rA = qmat(gens + [A], cols).rank()
    rD = qmat(gens + [delta], cols).rank()
    rAD = qmat(gens + [A, delta], cols).rank()
    log(dict(check='A_delta_mod_J6_exact', exact=True, odd_monomials=len(cols), delta_terms=len(delta), delta_parity=core.parity_of(delta),
             rank_J6odd=rJ, rank_J6odd_A=rA, rank_J6odd_delta=rD, rank_J6odd_A_delta=rAD,
             A_notin_J=(rA == rJ + 1), delta_notin_J=(rD == rJ + 1), independent_mod_J=(rAD == rJ + 2),
             h31_plus=len(cols) - rJ, seconds=round(time.time() - t0, 1)))


