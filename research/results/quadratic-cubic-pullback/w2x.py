# ---------------------------------------------------------------- Hilbert functions (parity-split)
def hilb_S(k, par=None):
    if k < 0:
        return 0
    if par is None:
        return comb(k + 5, 5)
    return sum(comb(k - j + 2, 2) * comb(j + 2, 2) for j in range(k + 1) if j % 2 == par)


_HR = None


def _hilbR_series(kmax=40):
    def pmul(x, y): return (x[0] * y[0] + x[1] * y[1], x[0] * y[1] + x[1] * y[0])
    def padd(x, y): return (x[0] + y[0], x[1] + y[1])
    def smul(s1, s2):
        out = [(0, 0)] * (kmax + 1)
        for i, a in enumerate(s1):
            if a == (0, 0): continue
            for j, b in enumerate(s2):
                if i + j > kmax: break
                if b == (0, 0): continue
                out[i + j] = padd(out[i + j], pmul(a, b))
        return out
    s1 = [(comb(n + 2, 2), 0) for n in range(kmax + 1)]
    s2 = [((comb(n + 2, 2), 0) if n % 2 == 0 else (0, comb(n + 2, 2))) for n in range(kmax + 1)]
    def binom_series(uflag):
        s = [(0, 0)] * (kmax + 1)
        for k in range(4):
            c = comb(3, k) * (-1) ** k
            if 5 * k <= kmax:
                s[5 * k] = padd(s[5 * k], (0, c) if (uflag and k % 2 == 1) else (c, 0))
        return s
    return smul(smul(binom_series(False), binom_series(True)), smul(s1, s2))


def hilb_R(k, par=None):
    """dim (S/J(F))_k restricted to Y-parity par (None = total); J(F) generated by a regular sequence of
    quintics, three Y-even and three Y-odd."""
    global _HR
    if _HR is None:
        _HR = _hilbR_series()
    if k < 0 or k > 40:
        return 0
    e, o = _HR[k]
    return e + o if par is None else (e if par == 0 else o)


def dim_J(k, par=None):
    return hilb_S(k, par) - hilb_R(k, par)


# ---------------------------------------------------------------- structural kernel of the fixed-D map
def structural_nullity(D, d=None):
    d = core.degree(D) if d is None else d
    pD = core.parity_of(D); pA = core.parity_of(A)
    pars = fixed_d.numerator_parities(D, A)
    parG = (pA - pD) % 2
    n = len(monomials(d, parG))
    n += sum(len(monomials(d - 5, pars[i])) for i in range(NV)) if d >= 5 else 0
    n -= len(monomials(d - 6, parG)) if d >= 6 else 0
    return n


# ---------------------------------------------------------------- rank-certified E1 test
def e1_certified(D, p):
    """Returns (e1_holds_mod_p, record).  record['rigorous_failure'] is True when the failure is certified."""
    ok, info = fixed_d.e1_solvable(F, A, q, D, p)
    d = core.degree(D)
    tpar = (core.parity_of(A) + core.parity_of(D)) % 2
    hj = dim_J(d + 6, tpar)
    rec = {'e1': ok, 'rankJ': info['rank'], 'hilbJ': hj, 'J_rank_certified': info['rank'] == hj, 'prime': p}
    rec['rigorous_failure'] = (not ok) and rec['J_rank_certified']
    return ok, rec


# ---------------------------------------------------------------- certified served space
def served_certified(D, p, margin=60, seed=3, want_basis=False, verbose=False):
    """Served-target space of D (Y-odd degree-6q targets), mod p, compressed rows; with rank certification.

    Returns dict: served (dim mod p), served_mod_J, A_served (mod p), rank_M, nullity_M, structural_nullity,
    certified (nullity_M == structural), cols, rows, seconds, and (if want_basis) the basis polys."""
    t0 = time.time()
    d = core.degree(D)
    A0 = {monomials(6 * q, 1)[0]: 1}
    S = fixed_d.FixedDSystem(F, A0, q, D, p, with_target_space=False, verbose=verbose)
    Dp = core.reduce_mod(D, p)
    D2 = mul(Dp, Dp, p)
    amons = monomials(6 * q, 1)
    CM = S.ncols
    for m in amons:
        S.cols.append(('A', -1, m)); S.colpolys.append(shift(D2, m, 1, p))
    for col in S.colpolys[CM:]:
        for e in col:
            if e not in S.rows:
                S.rows[e] = len(S.rows)
    S.nrows = len(S.rows); S.ncols = len(S.cols)
    M = fixed_d._sparse_matrix(S, with_rhs=False)
    C = S.ncols
    k = min(S.nrows, C + margin)
    Cm = fixed_d._compress(M, p, k, seed)
    del M
    t1 = time.time()
    Mn = nmod_mat(k, C, Cm.ravel().tolist(), p)
    del Cm
    X, nullity = Mn.nullspace()
    del Mn
    t2 = time.time()
    rank_MB = C - nullity
    a_idx = list(range(CM, C))
    basis = []
    if nullity == 0:
        served = 0
    else:
        proj = nmod_mat(len(a_idx), nullity, [int(X[j, kk]) for j in a_idx for kk in range(nullity)], p)
        T = proj.transpose()
        Tr, rk = T.rref()
        served = rk
        for i in range(rk):
            poly = {}
            for jj, m in enumerate(amons):
                v = int(Tr[i, jj])
                if v:
                    poly[m] = v
            basis.append(poly)
    del X
    rank_M = rank_MB - len(amons) + served
    nullity_M = CM - rank_M
    nstr = structural_nullity(D, d)
    # J part and A membership
    Jb = jacobian_part(1, p)
    rJ = rank_of(Jb, amons, p)
    rU = rank_of(Jb + basis, amons, p)
    Ap = core.reduce_mod(A, p)
    A_served = (rank_of(basis + [Ap], amons, p) == served) if served else False
    A_served_modJ = (rank_of(Jb + basis + [Ap], amons, p) == rU)
    rec = {'served': served, 'J_dim': rJ, 'served_mod_J': rU - rJ, 'A_served': A_served,
           'A_served_mod_J': A_served_modJ, 'rank_M': rank_M, 'nullity_M': nullity_M,
           'structural_nullity': nstr, 'certified': nullity_M == nstr, 'cols_M': CM, 'cols_total': C,
           'rows': S.nrows, 'k_compressed': k, 'prime': p, 'd': d,
           'seconds': round(time.time() - t0, 1), 't_build_compress': round(t1 - t0, 1), 't_null': round(t2 - t1, 1)}
    if want_basis:
        rec['basis'] = basis
    return rec


def jacobian_part(parity, p):
    Fp = core.reduce_mod(F, p)
    out = []
    for i in range(NV):
        Fi = pderiv(Fp, i, p)
        for j in range(NV):
            e = [0] * NV; e[j] = 1
            g = shift(Fi, tuple(e), 1, p)
            if core.parity_of(g) == parity:
                out.append(g)
    return out


def rank_of(polys, mons, p):
    if not polys:
        return 0
    col = {e: j for j, e in enumerate(mons)}
    flat = [0] * (len(polys) * len(mons))
    for r, P in enumerate(polys):
        for e, v in P.items():
            flat[r * len(mons) + col[e]] = v % p
    return nmod_mat(len(polys), len(mons), flat, p).rank()


# ---------------------------------------------------------------- candidate constructors
def var(i):
    return qcp.var(i)


def polar(w):
    """D = sum_i w_i dF/dz_i for a list of 6 polys w."""
    D = {}
    for i in range(NV):
        if w[i]:
            D = add(D, mul(w[i], pderiv(F, i)))
    return D


def gradpolar(h):
    """D = grad h . grad F."""
    return polar([pderiv(h, i) for i in range(NV)])


def euler(lam):
    """D = sum lam_i z_i dF/dz_i."""
    return polar([scale(var(i), lam[i]) if lam[i] else {} for i in range(NV)])


def delta_poly():
    return qcp.jac_det(Qs)


def full_test(name, family, D, p, log_path, note='', do_exact=True, margin=60):
    """E1 (certified) then certified served space; exact lift if A is served mod p.  Logs and returns the record."""
    t0 = time.time()
    d = core.degree(D)
    par = core.parity_of(D)
    rec = {'exp': 'fixedD', 'name': name, 'family': family, 'd': d, 'parity': par, 'prime': p, 'note': note,
           'D_terms': len(D), 'D_head': core.to_str(D)[:120]}
    if par is None:
        rec['result'] = 'skipped-mixed-parity'
        return logline(log_path, rec)
    divF, _ = jacobian.divisible_by(F, D, p)
    rec['F_divides_D'] = divF
    e1, e1rec = e1_certified(D, p)
    rec['e1'] = e1; rec['e1_rankJ'] = e1rec['rankJ']; rec['e1_hilbJ'] = e1rec['hilbJ']
    rec['e1_J_rank_certified'] = e1rec['J_rank_certified']
    inJ, _ = jacobian.in_jacobian(F, D, p)
    rec['D_in_J'] = inJ
    if not e1:
        rec['result'] = 'E1-fails' + ('-rigorous' if e1rec['rigorous_failure'] else '-modular')
        rec['seconds'] = round(time.time() - t0, 1)
        return logline(log_path, rec)
    sv = served_certified(D, p, margin=margin)
    rec.update({k: v for k, v in sv.items() if k != 'basis'})
    if sv['A_served']:
        rec['result'] = 'A-served-mod-p'
        if do_exact:
            out = fixed_d.solve_fixed_D_fast(F, A, q, D, p=p, verbose=False, want_exact=True)
            rec['exact'] = out.get('exact', False)
            if out.get('exact'):
                okv, vinfo = core.verify_witness(F, A, q, D, out['N'], out['Q'])
                rec['verified'] = okv
                if okv:
                    path = os.path.join(LANE, f'wave2-excl-WITNESS-{name}.json')
                    with open(path, 'w') as f:
                        json.dump({'id': qcp.IID, 'q': q, 'd': d, 'D': core.to_str(D), 'N': [core.to_str(n) for n in out['N']],
                                   'Q': core.to_str(out['Q'])}, f)
                    rec['witness_file'] = path
                    rec['result'] = 'WITNESS'
    else:
        rec['result'] = 'serves-' + ('nothing' if sv['served_mod_J'] == 0 else f"{sv['served_mod_J']}-classes-not-A") + \
                        ('-rigorous' if sv['certified'] else '-modular')
    rec['seconds'] = round(time.time() - t0, 1)
    return logline(log_path, rec)
