def hilbert_CI(k):
    """dim (S/J)_k for a CI of six quintics in six variables."""
    # coefficient of t^k in (1-t^5)^6/(1-t)^6
    from math import comb
    s = 0
    for j in range(7):
        m = k - 5 * j
        if m < 0: break
        s += (-1) ** j * comb(6, j) * comb(m + 5, 5)
    return s

def hilbert_CI_parity(k, par):
    """dim (S/J)_k^{par} using the Y-parity grading: generating function in (t, s) with s^2=1.
    S = Q[X0,X1,X2,Y0,Y1,Y2]; X has weight (1,0), Y weight (1,1) (parity); J generated by F_Xi (deg 5, par 0)
    and F_Yi (deg 5, par 1)."""
    # Count monomials of degree k and Y-degree b: C(k-b+2,2)*C(b+2,2)
    from math import comb
    def Smono(k, par):
        return sum(comb(k - b + 2, 2) * comb(b + 2, 2) for b in range(0, k + 1) if b % 2 == par) if k >= 0 else 0
    # Koszul: (S/J) = sum over subsets T of generators (-1)^|T| S(k - 5|T|) shifted by parity of T's Y-count
    s = 0
    for a in range(4):       # number of X-partials used
        for b in range(4):   # number of Y-partials used
            n = a + b
            s += (-1) ** n * comb(3, a) * comb(3, b) * Smono(k - 5 * n, (par - b) % 2)
    return s
