import sys, time
sys.path.insert(0, '/tmp/hodge/results/cyclic-triple-residual')
from w2core import *
F, A, q = load()
G = full_group(F, A)
S = Sect(F, A, G)
print('G order', S.order, 'gens', S.gens, 'chiA', S.chiA, 'chiE', S.chiE, flush=True)
# --- test 1: lane F, d=6, sector (0,0)
t0 = time.time()
r = e1_space(S, F, A, q, 6, (0, 0), verbose=True)
print({k: v for k, v in r.items() if k not in ('basis', 'Dm')}, flush=True)
fam = Family(S, F, A, q, 6, (0, 0), r['basis'], verbose=True)
print('check_direct', check_direct(fam), flush=True)
print('check_grad full', check_grad(fam), flush=True)
print('check_grad relax', check_grad(fam, relax=True), 'rank J_12 sector', fam.rank_J2d, 'rows', fam.nrows, flush=True)
c = fam.search(n_restarts=3, seed=1, verbose=True)
print('best rel', c[0]['rel'], 'spurious', c[0]['spurious'], flush=True)
cr = fam.search(n_restarts=3, seed=1, relax=True, verbose=True)
print('relax best rel', cr[0]['rel'], flush=True)
print('time', round(time.time() - t0, 1), flush=True)
# --- test 2: Fermat control at d=6, sector (0,0): D0 = X0^6+X1^6+X2^6 serves A (strict witness)
F0 = fermat()
S0 = Sect(F0, A, G)
r0 = e1_space(S0, F0, A, q, 6, (0, 0), verbose=True)
fam0 = Family(S0, F0, A, q, 6, (0, 0), r0['basis'], verbose=True)
print('fermat check_direct', check_direct(fam0), flush=True)
# value at D0 - F0/2 direction (orthogonal to F0 within the family)
Didx = {m: k for k, m in enumerate(fam0.Dm)}
import numpy as np
v = np.zeros(fam0.nD)
for mon, coef in core.parse('X0**6 + X1**6 + X2**6 - Y0**6 - Y1**6 - Y2**6').items():
    v[Didx[mon]] = float(coef)
a_target, *_ = np.linalg.lstsq(fam0.Dmat, v, rcond=None)
print('target in family? resid', np.linalg.norm(fam0.Dmat @ a_target - v), flush=True)
f, x, rr, b = fam0.value(a_target)
print('f at target', f, 'rel', f / (b @ b), flush=True)
c0 = fam0.search(n_restarts=6, seed=3, verbose=True)
print('fermat best rel', c0[0]['rel'], 'spurious', c0[0]['spurious'], flush=True)
res = promote(fam0, c0[0], F0, A, q, 'fermat-control', 'selftest')
for rec in res:
    print({k: v for k, v in rec.items() if k in ('descr', 'recon_err', 'e1', 'consistent', 'rank', 'rank_aug', 'verified', 'WITNESS', 'D')}, flush=True)
print('total time', round(time.time() - t0, 1), flush=True)
