#!/usr/bin/env python3
"""Splice the regenerated results table (table.md) into section 3 of the lane report."""
import re, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
subprocess.run([sys.executable, os.path.join(HERE, 'w2_final_table.py'), '--md', os.path.join(HERE, 'table.md')], capture_output=True)
table = open(os.path.join(HERE, 'table.md')).read()
path = '/tmp/hodge/notes/wave2-off-paired-search.md'
rep = open(path).read()
start = rep.index('## 3. Search inventory')
end = rep.index('Reading the table:')
head = rep[:start]
rep = head + "## 3. Search inventory (auto-generated by w2_final_table.py from all raw restart records)\n\n" + table + "\n" + rep[end:]
open(path, 'w').write(rep)
print('report table refreshed')
