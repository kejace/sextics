def parse_gb(path, nt):
    txt = open(path).read()
    i = txt.find('['); j = txt.rfind(']')
    body = txt[i + 1:j]
    polys = [s.strip() for s in body.replace('\n', '').split(',') if s.strip()]
    lead = []
    for P in polys:
        first = P.split('+')[0]
        e = [0] * nt
        for part in first.split('*')[1:]:
            m = re.match(r't(\d+)\^(\d+)', part)
            if m: e[int(m.group(1))] = int(m.group(2))
        lead.append(tuple(e))
    return polys, lead

def hilbert_vanishing_degree(lead, nt, cap=40):
    """Smallest delta with no standard monomial of degree delta (monomial ideal generated by `lead`), or None."""
    gens = [l for l in lead if any(l)]
    if any(all(v == 0 for v in l) for l in lead):
        return 0
    def divisible(m):
        return any(all(m[i] >= g[i] for i in range(nt)) for g in gens)
    # standard monomials degree by degree (only feasible for small nt or quick vanishing)
    for delta in range(0, cap):
        cnt = 0
        # enumerate monomials of degree delta over nt variables lazily; bail out when count exceeds a bound
        for comb in itertools.combinations(range(delta + nt - 1), nt - 1):
            e = []; prev = -1
            for x in comb: e.append(x - prev - 1); prev = x
            e.append(delta + nt - 2 - prev)
            if not divisible(tuple(e)):
                cnt += 1
                break
        if cnt == 0:
            return delta
        if nt > 12 and delta >= 6:
            return None
    return None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--d', type=int, required=True); ap.add_argument('--chars', default='all'); ap.add_argument('--job', required=True)
    ap.add_argument('--prime', type=int, default=WB.PM); ap.add_argument('--threads', type=int, default=1); ap.add_argument('--timeout', type=int, default=600)
    ap.add_argument('--tsub', default='all'); ap.add_argument('--no-rational', action='store_true'); ap.add_argument('--outdir', default=None)
    a = ap.parse_args()
    F, A, q = w2lib.load(); cA = char_of(A); p = a.prime
    chars = [(x, y) for x in range(6) for y in range(6)] if a.chars == 'all' else [(int(s[0]), int(s[1])) for s in a.chars.split(',')]
    outdir = a.outdir or f'{w2lib.PK}/relax_{a.job}'; os.makedirs(outdir, exist_ok=True)
    recfile = f'{w2lib.PK}/receipts_{a.job}.jsonl'
    Fi = [pderiv(F, i) for i in range(NV)]
    for c in chars:
        t0 = time.time()
        sysd, info = WB.build_fast(F, A, q, a.d, c, p, 'relaxJ', a.tsub, addJ=False, verbose=False)
        base = {'exp': 'relaxJ-gb', 'job': a.job, 'd': a.d, 'char': c, 'tsub': a.tsub, 'prime': p, 'family': f'all D in sector ({a.tsub})',
                'nt': info.get('nt'), 'nQ': info.get('neq_nonzero'), 'ring_dim_2d': info.get('ring_dim_2d')}
        def emit(rec):
            rec['seconds'] = round(time.time() - t0, 1)
            w2lib.log(rec); open(recfile, 'a').write(json.dumps(rec, default=str) + '\n')
            print(json.dumps({k: rec.get(k) for k in ('d', 'char', 'nt', 'nQ', 'gb_size', 'pure_powers', 'vanishing_degree', 'rational_verified', 'result', 'seconds')}, default=str), flush=True)
        if sysd is None:
            emit(dict(base, result='PROVEN-empty-sector(colon dim 0 mod p bounds the rational colon dim)')); continue
        nt = sysd['nt']
        # msolve input: homogeneous quadrics in t
        names = [f't{i}' for i in range(nt)]
        polys = []
        for eq in sysd['eqs']:
            terms = []
            for (k1, i1, k2, i2), cf in eq.items():
                if not cf: continue
                terms.append(f'{cf}*t{i1}*t{i2}' if i1 != i2 else f'{cf}*t{i1}^2')
            if terms: polys.append('+'.join(terms))
        tag = f'd{a.d}_c{c[0]}{c[1]}_{a.tsub}'
        path = f'{outdir}/{tag}.ms'
        open(path, 'w').write(','.join(names) + '\n' + str(p) + '\n' + ',\n'.join(polys) + '\n')
        out = path.replace('.ms', '.gb')
        try:
            r = subprocess.run(['msolve', '-g', '2', '-f', path, '-o', out, '-t', str(a.threads), '-v', '0'], capture_output=True, text=True, timeout=a.timeout)
        except subprocess.TimeoutExpired:
            emit(dict(base, result='msolve-timeout')); continue
        if not os.path.exists(out):
            emit(dict(base, result='msolve-failed', stderr=r.stderr[-300:])); continue
        gpolys, lead = parse_gb(out, nt)
        pure = {}
        for l in lead:
            nz = [i for i in range(nt) if l[i]]
            if len(nz) == 1: pure[nz[0]] = min(pure.get(nz[0], 10**9), l[nz[0]])
        mprimary = all(i in pure for i in range(nt)) or any(all(v == 0 for v in l) for l in lead)
        vdeg = hilbert_vanishing_degree(lead, nt) if mprimary else None
        rec = dict(base, gb_size=len(gpolys), pure_powers=[pure.get(i) for i in range(nt)], mprimary=mprimary, vanishing_degree=vdeg)
        if not mprimary:
            emit(dict(rec, result='relaxation-not-mprimary-modp(no exclusion from relaxJ alone)')); continue
        if a.no_rational:
            emit(dict(rec, rational_verified=False, result='mprimary-modp(rational data not verified)')); continue
        # rational verification of D_a, N_a and of the functionals ell_r
        try:
            Dq, Nq, _ = WC.rational_data(F, A, q, sysd['Ds'], sysd['Ns'], [], p)
        except ValueError as ex:
            emit(dict(rec, rational_verified=False, result=f'mprimary-modp but rational data failed: {ex}')); continue
        sector = cadd(cA, cadd(c, c)); mons2d = monos_char(2 * a.d, sector)
        Fp = reduce_mod(F, p); Fip = [pderiv(Fp, i, p) for i in range(NV)]
        Jg_p = [shift(Fip[i], m, 1, p) for i in range(NV) for m in monos_char(2 * a.d - 5, cadd(sector, VARCHAR[i]))]
        Jg_q = [shift(Fi[i], m, 1) for i in range(NV) for m in monos_char(2 * a.d - 5, cadd(sector, VARCHAR[i]))]
        red = w2_fast.MatReducer(Jg_p, mons2d, p)
        ells = []; ok = True; maxh = 0
        for r_ in range(red.nstd):
            lam = {r_: 1}
            ell = WC.functional_from_lambda(lam, red, p)
            if ell is None: ok = False; break
            for v in ell.values(): maxh = max(maxh, abs(v.numerator), v.denominator)
            if any(WC.apply_functional(ell, g) != 0 for g in Jg_q): ok = False; break
            ells.append(ell)
        if not ok:
            emit(dict(rec, rational_verified=False, result='mprimary-modp but functional reconstruction/verification failed')); continue
        # exact rational quadrics reduce to the modular ones?  (check all coefficients when nt <= 60)
        same = None
        if nt <= 60:
            EB = WC.ExactB(Dq, Nq, [])
            same = True
            modeqs = sysd['eqs']
            # rebuild modular eq dicts keyed by (a,b) for comparison: eqs are per standard index; recompute from EB
            qq = {}
            for r_, ell in enumerate(ells):
                for aa in range(nt):
                    for bb in range(nt):
                        v = WC.apply_functional(ell, EB.B(aa, 't', bb))
                        if v:
                            key = (min(aa, bb), max(aa, bb))
                            qq.setdefault(r_, {}); qq[r_][key] = qq[r_].get(key, 0) + v
            # modular comparison: the modular eqs list is in std order with zero rows dropped; compare as sets of reduced dicts
            def red_mod(dct):
                out = {}
                for k, v in dct.items():
                    vv = (v.numerator * pow(v.denominator, -1, p)) % p if isinstance(v, Fraction) else v % p
                    if vv: out[k] = vv
                return out
            setQ = {json.dumps(sorted(red_mod(dct).items())) for dct in qq.values() if red_mod(dct)}
            setP = {json.dumps(sorted({(k[1], k[3]): v for k, v in eq.items()}.items())) for eq in modeqs}
            same = (setQ == setP)
        emit(dict(rec, rational_verified=True, rational_reduction_matches=same, ell_max_height=maxh,
                  result='PROVEN-no-denominator-in-sector(relaxJ m-primary mod p => over Q)' if same is not False else 'mprimary-modp but rational quadrics differ from modular ones'))

if __name__ == '__main__':
    main()
