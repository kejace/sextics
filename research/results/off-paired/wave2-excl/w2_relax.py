"""Rigorous sector exclusion through the homogeneous Jacobian-relaxation quadrics.

For a sector (d, c): D = sum_a t_a D_a (D_a: rational basis of the colon sector modulo the Euler gauge, verified exactly:
N_a(F) = A D_a), the Euler-normalized certificate has N = sum_a t_a N_a + S with S in the Koszul kernel, and
B_D(N) == 0 (mod F).  Since B_D(S) lies in J(F) for Koszul S and F in J(F), every certificate satisfies
      B_{D(t)}(N(t)) == 0  (mod J(F)_{2d}),      N(t) = sum_a t_a N_a,
i.e. the pure-t quadrics  Q_r(t) = ell_r(B_{D(t)}(N(t))) = 0  for a rational basis {ell_r} of the annihilator of J(F)_{2d}[sector].
THEOREM (transfer): the ideal I = (Q_r) in Q[t] is homogeneous.  If the reduced Groebner basis of I mod p contains a pure power
of every variable, then (S/I_p)_delta = 0 for some delta, i.e. the degree-delta Macaulay matrix of the generators has full
column rank mod p, hence over Q; so (I_Q)_delta = S_delta and V_C(I) = {0}: every certificate has t = 0, i.e. D in the gauge
F*S_{d-6}, which is not a legal denominator.  Only the rational data (D_a, N_a, ell_r) need exact verification -- done here.
usage: python3 w2_relax.py --d 8 --chars all|00,20 --job NAME [--prime P] [--threads T] [--timeout S] [--full]
"""
