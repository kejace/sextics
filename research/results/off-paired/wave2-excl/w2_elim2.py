"""EXACT sector exclusion, relaxation-first (all over Q; modular arithmetic only to FIND rational objects, which are then verified).

1. Rational data D_a, N_a, S_k (verified), exact B products, exact normal forms modulo F*S_{2d-6}[sector]  (as w2_elim.py).
2. Degree-2 relaxation over Q: lambda with lambda^T M_a = 0 for all a (M_a = s-coefficient block of D_a), found mod p, reconstructed,
   VERIFIED exactly; quadrics g_lambda(t) = lambda^T q(t) in Q[t].  Every certificate with D = sum t_a D_a satisfies g_lambda(t) = 0.
3. Singular over Q: std / dim of J2 = (g_lambda).  dim 0 (affine cone {0}) => PROVEN.  Otherwise minAssGTZ(J2) over Q: the components.
4. Each component P: if generated by linear forms, W = V(P) is a rational subspace with basis v_1..v_w.
   w = 1: D = sum v_a D_a is a single rational denominator: rigorous fixed-D receipt (w2lib).  w >= 2: restricted bilinear system in
   (x_1..x_w, s) with t = sum x_i v_i, exact; Singular eliminate(s) over Q; m-primary in x => no certificate on W.
   Nonlinear components are reported (not excluded here).
usage: python3 w2_elim2.py --d 7 --chars 00 --job NAME [--timeout S]
"""
import sys, os, json, time, argparse, subprocess, re
sys.path.insert(0, '/tmp/hodge/results/off-paired/wave2-excl')
import w2lib, w2_bilinear as WB, w2_cert as WC, w2_elim as WE
from w2lib import char_of, cadd, monos_char
from hodge import core
from hodge.core import NV, shift, reduce_mod, add, scale, pderiv
from fractions import Fraction
from flint import fmpq_mat, fmpq, nmod_mat, fmpz_mat, fmpz

def frac_str(v):
    return f'({v.numerator}/{v.denominator})' if v.denominator != 1 else f'({v.numerator})'

def run_singular(script, timeout):
    path = script
    try:
        r = subprocess.run(['Singular', '-q', path], capture_output=True, text=True, timeout=timeout)
        return r.stdout, None
    except subprocess.TimeoutExpired:
        return None, 'timeout'

def parse_components(out):
    """Parse lines 'COMP i: p1 ; p2 ; ...' """
    comps = []
    for line in out.splitlines():
        if line.startswith('COMP '):
            body = line.split(':', 1)[1].strip()
            comps.append([s.strip() for s in body.split(';') if s.strip()])
    return comps

def linear_component_basis(polys, nt):
    """If all polys are linear forms in t, return a rational basis (list of Fraction vectors) of their common kernel, else None."""
    rows = []
    for P in polys:
        row = [Fraction(0)] * nt
        # parse Singular polynomial string: terms like 3*t2, -1/2*t5, t7, (numbers)
        s = P.replace(' ', '')
        for term in re.findall(r'[+-]?[^+-]+', s):
            if not term: continue
            m = re.match(r'([+-]?)(\d+(?:/\d+)?)?\*?t(\d+)(\^(\d+))?$', term)
            if not m:
                return None
            if m.group(4): return None
            sign = -1 if m.group(1) == '-' else 1
            coef = Fraction(m.group(2)) if m.group(2) else Fraction(1)
            row[int(m.group(3))] += sign * coef
        rows.append(row)
    M = fmpq_mat(len(rows), nt)
    for i, row in enumerate(rows):
        for j, v in enumerate(row): M[i, j] = fmpq(v.numerator, v.denominator)
    Mr, rank = M.rref()
    piv = []
    for i in range(rank):
        j = 0
        while j < nt and Mr[i, j] == 0: j += 1
        piv.append(j)
    free = [j for j in range(nt) if j not in piv]
    basis = []
    for f in free:
        v = [Fraction(0)] * nt; v[f] = Fraction(1)
        for i, j in enumerate(piv):
            v[j] = -Fraction(int(Mr[i, f].p), int(Mr[i, f].q))
        basis.append(v)
    return basis

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--d', type=int, required=True); ap.add_argument('--chars', required=True); ap.add_argument('--job', required=True)
    ap.add_argument('--timeout', type=int, default=1800); ap.add_argument('--prime', type=int, default=WB.PM); ap.add_argument('--tsub', default='all')
    ap.add_argument('--direct', action='store_true'); ap.add_argument('--skip-Q', action='store_true')
    a = ap.parse_args()
    F, A, q = w2lib.load(); cA = char_of(A); p = a.prime
    chars = [(x, y) for x in range(6) for y in range(6)] if a.chars == 'all' else [(int(s[0]), int(s[1])) for s in a.chars.split(',')]
    outdir = f'{w2lib.PK}/elim2_{a.job}'; os.makedirs(outdir, exist_ok=True)
    recfile = f'{w2lib.PK}/receipts_{a.job}.jsonl'
    for c in chars:
        t0 = time.time()
        sysd, info = WB.build_fast(F, A, q, a.d, c, p, 'sector', a.tsub, addJ=False, verbose=False)
        base = {'exp': 'elim2Q', 'job': a.job, 'd': a.d, 'char': c, 'tsub': a.tsub, 'family': f'all D in sector ({a.tsub})', 'nt': info.get('nt'), 'ns': info.get('ns')}
        def emit(rec):
            rec['seconds'] = round(time.time() - t0, 1)
            w2lib.log(rec); open(recfile, 'a').write(json.dumps(rec, default=str) + '\n')
            print(json.dumps({k: rec.get(k) for k in ('d', 'char', 'nt', 'ns', 'relax_dim', 'n_quadrics', 'dim_J2', 'components', 'result', 'seconds')}, default=str), flush=True)
        if sysd is None:
            emit(dict(base, result='PROVEN-empty-sector(colon dim 0 mod p bounds the rational colon dim)')); continue
        try:
            Dq, Nq, Sq = WC.rational_data(F, A, q, sysd['Ds'], sysd['Ns'], sysd['syz'], p)
        except ValueError as ex:
            # two-prime CRT retry: rebuild the bases at a second prime, align D's by leading monomial, CRT entrywise
            try:
                p2 = w2lib.P1 if p != w2lib.P1 else w2lib.P2
                sysd2, info2 = WB.build_fast(F, A, q, a.d, c, p2, 'sector', a.tsub, addJ=False, verbose=False)
                lead = lambda D: max(D)
                byl2 = {lead(D): (D, N) for D, N in zip(sysd2['Ds'], sysd2['Ns'])}
                Dq, Nq = [], []
                for D, N in zip(sysd['Ds'], sysd['Ns']):
                    D2, N2 = byl2[lead(D)]
                    # normalize both to leading coefficient 1 (rref vectors already have unit pivots)
                    d_ = WC.crt_poly(D, p, (p2, D2))
                    if d_ is None: raise ValueError('CRT D reconstruction failed')
                    n_ = [WC.crt_poly(N[i], p, (p2, N2[i])) for i in range(NV)]
                    if any(x is None for x in n_):
                        n_ = WC.exact_lift(F, A, q, d_)
                        if n_ is None: raise ValueError('exact lift failed')
                    Dq.append(d_); Nq.append(n_)
                _, _, Sq = WC.rational_data(F, A, q, [], [], sysd['syz'], p)
                # verify lifts exactly
                Fi_ = [pderiv(F, i) for i in range(NV)]
                for d_, n_ in zip(Dq, Nq):
                    lhs = {}
                    for i in range(NV): lhs = add(lhs, core.mul(n_[i], Fi_[i]))
                    if lhs != core.mul(A, d_): raise ValueError('CRT lift verification failed')
                base['rational_data'] = 'two-prime CRT'
            except Exception as ex2:
                emit(dict(base, result=f'rational-data-failed: {ex}; CRT retry: {ex2}')); continue
        nt, ns = len(Dq), len(Sq)
        EB = WC.ExactB(Dq, Nq, Sq)
        sector = cadd(cA, cadd(c, c)); mons2d = monos_char(2 * a.d, sector); mons_low = monos_char(2 * a.d - 6, sector)
        red = WE.RatReducer([shift(F, m, 1) for m in mons_low], mons2d)
        # exact equations: eq[r] = {(i,j): coeff}, i,j < nt for t-t, j >= nt for t-s
        eqs = {}
        def addeq(coords, key):
            for r, v in coords.items():
                eqs.setdefault(r, {}); eqs[r][key] = eqs[r].get(key, 0) + v
        for aa in range(nt):
            for bb in range(nt):
                addeq(red.coords(EB.B(aa, 't', bb)), (min(aa, bb), max(aa, bb)))
            for k in range(ns):
                addeq(red.coords(EB.B(aa, 's', k)), (aa, nt + k))
        eqs = [e for e in eqs.values() if any(e.values())]
        neq = len(eqs)
        # degree-2 relaxation over Q: left kernel of C_y (neq x nt*ns), EXACT: integer matrix (denominators cleared per column),
        # integer nullspace (fmpz_mat), LLL-reduced to keep coefficients small.
        R, C = nt * ns, neq
        lams = []
        if R:
            from math import lcm
            dens = [1] * C
            for r, e in enumerate(eqs):
                for (i, j), v in e.items():
                    if j >= nt: dens[r] = lcm(dens[r], v.denominator)
            Mz = fmpz_mat(R, C)
            for r, e in enumerate(eqs):
                for (i, j), v in e.items():
                    if j >= nt:
                        Mz[i * ns + (j - nt), r] = fmpz(int(v * dens[r]))
            X, nul = Mz.nullspace()          # columns of X (first nul) span the kernel over Q, integer entries
            K = fmpz_mat(nul, C, [int(X[r, k]) for k in range(nul) for r in range(C)])
            if nul:
                K = K.lll()
            for k in range(nul):
                lam = [Fraction(int(K[k, r])) * dens[r] for r in range(C)]   # lambda_r (true coefficient on eq_r) = K * dens
                lams.append(lam)
        else:
            lams = [[Fraction(1 if r == k else 0) for r in range(C)] for k in range(C)]
        ok = True
        # exact verification and quadrics
        quads = []
        for lam in lams:
            Qd = {}
            ok = True
            for r, e in enumerate(eqs):
                if lam[r] == 0: continue
                for (i, j), v in e.items():
                    if j >= nt:
                        Qd_s = None
                    key = (i, j)
                    Qd[key] = Qd.get(key, 0) + lam[r] * v
            # s-part must vanish exactly
            if any(v != 0 for (i, j), v in Qd.items() if j >= nt):
                emit(dict(base, neq=neq, result='lambda exact verification FAILED')); ok = False; break
            Qd = {k: v for k, v in Qd.items() if v != 0 and k[1] < nt}
            if Qd: quads.append(Qd)
        if not ok: continue
        if a.direct:
            tt = [f't{i}' for i in range(nt)]; ss = [f's{k}' for k in range(ns)]
            def vn(i): return f't{i}' if i < nt else f's{i - nt}'
            polys_I = ['+'.join(f'{frac_str(v)}*{vn(i)}*{vn(j)}' for (i, j), v in e.items() if v) for e in eqs]
            polys_Q = ['+'.join(f'{frac_str(v)}*t{i}*t{j}' for (i, j), v in Qd.items()) for Qd in quads]
            singd = f'''ring r = 0, ({",".join(tt + ss)}), dp;
ideal I = {",\n".join(polys_Q + polys_I)};
poly ps = {"*".join(ss) if ss else "1"};
ideal E = eliminate(I, ps);
ideal G = std(E);
print("DIME " + string(dim(G)));
print("NGENS " + string(size(E)));
quit;
'''
            spathd = f'{outdir}/d{a.d}_c{c[0]}{c[1]}_direct.sing'; open(spathd, 'w').write(singd)
            outd, errd = run_singular(spathd, a.timeout)
            if outd is None:
                emit(dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), result='singular-timeout(direct eliminate I+J2)')); continue
            md = re.search(r'DIME (-?\d+)', outd)
            dme = int(md.group(1)) if md else None
            rec = dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), elim_dim_t=(dme - ns) if dme is not None else None)
            rec['result'] = 'PROVEN-no-denominator-in-sector(exact elimination over Q of I+J2: E m-primary)' if (dme is not None and dme - ns <= 0) else f'elimination ideal positive-dimensional ({None if dme is None else dme - ns})'
            emit(rec); continue
        # FAST exact test by transfer: the quadrics are exact rational elements of E = I ∩ Q[t]; the ideal they generate is homogeneous,
        # so if its reduction mod p is m-primary (pure power of each variable among the GB leading monomials, msolve) then it is
        # m-primary over Q (Hilbert function over Q <= Hilbert function mod p).
        import w2_relax as WR, subprocess as _sp
        mp = a.prime
        def red_q(v): return (v.numerator * pow(v.denominator, -1, mp)) % mp
        polys_p = []
        for Qd in quads:
            terms = [f'{red_q(v)}*t{i}*t{j}' if i != j else f'{red_q(v)}*t{i}^2' for (i, j), v in Qd.items() if red_q(v)]
            if terms: polys_p.append('+'.join(terms))
        mpath = f'{outdir}/d{a.d}_c{c[0]}{c[1]}_J2modp.ms'
        open(mpath, 'w').write(','.join(f't{i}' for i in range(nt)) + '\n' + str(mp) + '\n' + ',\n'.join(polys_p) + '\n')
        mout = mpath.replace('.ms', '.gb'); mprim = None
        try:
            _sp.run(['msolve', '-g', '2', '-f', mpath, '-o', mout, '-t', '1', '-v', '0'], capture_output=True, text=True, timeout=min(a.timeout, 600))
            gpolys, lead = WR.parse_gb(mout, nt)
            pure = {}
            for l in lead:
                nz = [i for i in range(nt) if l[i]]
                if len(nz) == 1: pure[nz[0]] = min(pure.get(nz[0], 10**9), l[nz[0]])
            mprim = all(i in pure for i in range(nt))
        except Exception as ex:
            mprim = None
        if mprim:
            emit(dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), lambda_basis='lll-integer-kernel', mprimary_modp=True,
                      result='PROVEN-no-denominator-in-sector(exact quadrics; m-primary mod p => m-primary over Q by transfer)')); continue
        names = [f't{i}' for i in range(nt)]
        qstr = ['+'.join(f'{frac_str(v)}*t{i}*t{j}' for (i, j), v in Qd.items()) for Qd in quads]
        sing = f'''LIB "primdec.lib";
ring r = 0, ({",".join(names)}), dp;
ideal J2 = {",\n".join(qstr) if qstr else "0"};
ideal G = std(J2);
int dm = dim(G);
print("DIMJ2 " + string(dm));
if (dm > 0) {{
  list L = minAssGTZ(J2);
  int i; int j;
  for (i = 1; i <= size(L); i++) {{
    string s = "COMP " + string(i) + ":";
    for (j = 1; j <= size(L[i]); j++) {{ s = s + " " + string(L[i][j]) + " ;"; }}
    print(s);
  }}
}}
quit;
'''
        spath = f'{outdir}/d{a.d}_c{c[0]}{c[1]}_J2.sing'; open(spath, 'w').write(sing)
        out, err = (None, 'skipped') if a.skip_Q else run_singular(spath, a.timeout)
        if out is None:
            # fallback: certified linear span of V(J2) over Q + localized exact relaxation on it
            import w2_span, w2_local
            basis_L, sinfo = w2_span.certify_span(quads, nt, a.prime, outdir, timeout=min(a.timeout, 900))
            if basis_L is None:
                emit(dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), span_info=sinfo, result='singular-timeout(J2); span certification failed')); continue
            w = len(basis_L)
            restricted = w2_local.restrict(eqs, nt, ns, basis_L)
            degs = (2, 3) if w > 8 else (2, 3, 4)
            cons = w2_local.consequences(restricted, w, ns, degrees=degs)
            allc = [g for k in cons for g in cons[k]['consequences']]
            xs = [f'x{i}' for i in range(w)]
            def mstr(m): return '*'.join(f'x{i}^{e}' if e > 1 else f'x{i}' for i, e in enumerate(m) if e) or '1'
            cstr = ['+'.join(f'{frac_str(v)}*{mstr(m)}' for m, v in g.items()) for g in allc]
            sing5 = f'''ring r = 0, ({",".join(xs)}), dp;
ideal C = {",\n".join(cstr) if cstr else "0"};
ideal G = std(C);
print("DIMC " + string(dim(G)));
quit;
'''
            spath5 = f'{outdir}/d{a.d}_c{c[0]}{c[1]}_span_local.sing'; open(spath5, 'w').write(sing5)
            out5, err5 = run_singular(spath5, a.timeout)
            m5 = re.search(r'DIMC (-?\d+)', out5) if out5 else None
            dmc = int(m5.group(1)) if m5 else None
            okc = (dmc is not None and dmc <= 0)
            emit(dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), lambda_basis='lll-integer-kernel', span_info=sinfo,
                      span_dim=w, local_relax={k: {kk: vv for kk, vv in cons[k].items() if kk != 'consequences'} | {'n': len(cons[k]['consequences'])} for k in cons},
                      local_dim=dmc, result=('PROVEN-no-denominator-in-sector(exact: certified span of V(J2) + localized relaxation m-primary)' if okc else 'span certified but localized relaxation not m-primary')))
            continue
        m = re.search(r'DIMJ2 (-?\d+)', out)
        if not m:
            emit(dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), result='singular-failed', stderr=out[-300:])); continue
        dm = int(m.group(1))
        rec = dict(base, neq=neq, relax_dim=len(lams), n_quadrics=len(quads), dim_J2=dm, lambda_basis='lll-integer-kernel')
        if dm <= 0:
            emit(dict(rec, result='PROVEN-no-denominator-in-sector(exact: degree-2 relaxation ideal over Q is m-primary)')); continue
        comps = parse_components(out)
        rec['components'] = len(comps)
        comp_results = []
        all_ok = True
        for ci, polys in enumerate(comps):
            basis = linear_component_basis(polys, nt)
            if basis is None or len(basis) >= 2:
                # localized relaxation on the linear span L of the component (= the component itself if linear)
                import w2_local
                lin = [P_ for P_ in polys if re.fullmatch(r'[\s+\-*/0-9t^]+', P_) and '^' not in P_ and all(('*' not in term or term.count('t') <= 1) for term in re.findall(r'[+-]?[^+-]+', P_.replace(' ', ''))) and P_.count('t') == len(re.findall(r'[+-]?[^+-]+', P_.replace(' ', '')))]
                span = basis if basis is not None else (linear_component_basis(lin, nt) if lin else [[Fraction(1 if i == j else 0) for i in range(nt)] for j in range(nt)])
                w = len(span)
                restricted = w2_local.restrict(eqs, nt, ns, span)
                degs = (2, 3) if w > 8 else (2, 3, 4)
                cons = w2_local.consequences(restricted, w, ns, degrees=degs)
                allc = [g for k in cons for g in cons[k]['consequences']]
                xs = [f'x{i}' for i in range(w)]
                def mstr(m): return '*'.join(f'x{i}^{e}' if e > 1 else f'x{i}' for i, e in enumerate(m) if e) or '1'
                cstr = ['+'.join(f'{frac_str(v)}*{mstr(m)}' for m, v in g.items()) for g in allc]
                sing4 = f'''ring r = 0, ({",".join(xs)}), dp;
ideal C = {",\n".join(cstr) if cstr else "0"};
ideal G = std(C);
print("DIMC " + string(dim(G)));
quit;
'''
                spath4 = f'{outdir}/d{a.d}_c{c[0]}{c[1]}_comp{ci}_local.sing'; open(spath4, 'w').write(sing4)
                out4, err4 = run_singular(spath4, a.timeout)
                m4 = re.search(r'DIMC (-?\d+)', out4) if out4 else None
                dmc = int(m4.group(1)) if m4 else None
                okc = (dmc is not None and dmc <= 0)
                comp_results.append({'comp': ci, 'linear': basis is not None, 'span_dim': w, 'relax': {k: {kk: vv for kk, vv in cons[k].items() if kk != 'consequences'} | {'n': len(cons[k]['consequences'])} for k in cons},
                                     'local_dim': dmc, 'proven': okc})
                if not okc: all_ok = False
                continue
            w = len(basis)
            if w == 1:
                v = basis[0]
                D = {}
                for aa, x in enumerate(v):
                    if x: D = add(D, scale(Dq[aa], x))
                r1 = w2lib.fixedD_receipt_certified(F, A, q, D, w2lib.P1, label=f'relax-residual d{a.d} c{c} comp{ci}', family='relaxation-residual-line')
                r1.pop('x', None); r1.pop('S', None)
                w2lib.log(dict(r1, job=a.job))
                comp_results.append({'comp': ci, 'linear': True, 'dim': 1, 'fixedD': r1['result'], 'rank_M': r1['rank_M'], 'rank_aug': r1['rank_aug'], 'nullity': r1['nullity'], 'explicit_kernel': r1['explicit_kernel']})
                if not str(r1['result']).startswith('PROVEN'): all_ok = False
        rec['component_results'] = comp_results
        rec['result'] = 'PROVEN-no-denominator-in-sector(exact: relaxation components each excluded over Q)' if all_ok else 'residual components not all excluded (see component_results)'
        emit(rec)

if __name__ == '__main__':
    main()
