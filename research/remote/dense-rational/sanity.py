# catalecticant ranks: span of k-th partials of F in S_{6-k}
Fp = core.reduce_mod(F, p)
def partials(Pl, k):
    cur = {(): Pl}
    for _ in range(k):
        nxt = {}
        for key, poly in cur.items():
            for i in range(NV):
                if key and i < key[-1]:
                    continue
                nxt[key + (i,)] = pderiv(poly, i, p)
        cur = nxt
    return list(cur.values())
for k in range(1, 6):
    polys = partials(Fp, k)
    mons = monomials(6 - k)
    idx = {m: j for j, m in enumerate(mons)}
    M = nmod_mat(len(polys), len(mons), [0]*(len(polys)*len(mons)), p)
    for i, poly in enumerate(polys):
        for e, v in poly.items():
            M[i, idx[e]] = v
    print(f'catalecticant: {k}-th partials: count={len(polys)} rank={M.rank()} (generic max {min(len(polys), len(mons))})')
# stabilizer Lie algebra: M in gl_6, lambda:  sum_ij M_ij Z_i d_j F - lambda F = 0
Fi = [pderiv(Fp, i, p) for i in range(NV)]
cols = []
for i in range(NV):
    for j in range(NV):
        e = [0]*NV; e[i] = 1
        cols.append(shift(Fi[j], tuple(e), 1, p))
cols.append(scale(Fp, p-1, p))
rows = {}
for c in cols:
    for e in c: rows.setdefault(e, len(rows))
M = nmod_mat(len(rows), len(cols), [0]*(len(rows)*len(cols)), p)
for j, c in enumerate(cols):
    for e, v in c.items(): M[rows[e], j] = v
X, nullity = M.nullspace()
print('stabilizer Lie algebra {M: M.F = lambda F}: dim =', nullity, '(1 = Euler only)')
