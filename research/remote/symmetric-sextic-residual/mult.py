"""Equivariant Hilbert function of the Jacobian ring R under G = S3(X) x S3(Y) (x tau-parity), computed in the
Fermat monomial model (same characters for every smooth G-invariant F since J is generated by a regular sequence
transforming as V^*).  Then the representation-forced lower bound for ker([A]: R_d -> R_{d+6}) per isotypic type."""
import itertools
from collections import Counter
# S3 irreps characters by cycle type: triv, sign, std ; classes: e (1), transposition (3), 3-cycle (2)
chars = {'triv': {'e':1,'t':1,'c':1}, 'sign': {'e':1,'t':-1,'c':1}, 'std': {'e':2,'t':0,'c':-1}}
sizes = {'e':1,'t':3,'c':2}
perms = {'e': (0,1,2), 't': (1,0,2), 'c': (1,2,0)}
def fixed_count(d, par, gx, gy):
    """number of monomials of degree d, Y-parity par, exponents <=4, fixed by (gx, gy); note the action on
    monomials is a permutation action so the character is the number of fixed monomials."""
    cnt = 0
    for e in itertools.product(range(5), repeat=6):
        if sum(e) != d or (e[3]+e[4]+e[5]) % 2 != par: continue
        ex = e[:3]; ey = e[3:]
        px, py = perms[gx], perms[gy]
        if tuple(ex[px[i]] for i in range(3)) == ex and tuple(ey[py[i]] for i in range(3)) == ey:
            cnt += 1
    return cnt
def mults(d, par):
    out = {}
    for rx in chars:
        for ry in chars:
            s = 0
            for gx in sizes:
                for gy in sizes:
                    s += sizes[gx]*sizes[gy]*chars[rx][gx]*chars[ry][gy]*fixed_count(d, par, gx, gy)
            out[(rx, ry)] = s // 36
    return out
rows = []
for d in range(0, 25):
    for par in (0, 1):
        m = mults(d, par)
        tot = sum(m[(rx,ry)]*chars[rx]['e']*chars[ry]['e'] for rx in chars for ry in chars)
        rows.append((d, par, m, tot))
# multiplication by A (invariant, odd) maps R_d^{par} -> R_{d+6}^{1-par}; forced kernel per irrep = max(0, m_d - m_{d+6})
print('d par | triv.triv sign.sign triv.sign sign.triv std.triv triv.std std.std std.sign sign.std | dim')
M = {(d, par): m for d, par, m, tot in rows}
for d, par, m, tot in rows:
    print(f'{d:2d} {par} |', ' '.join(f'{m[k]:4d}' for k in [("triv","triv"),("sign","sign"),("triv","sign"),("sign","triv"),("std","triv"),("triv","std"),("std","std"),("std","sign"),("sign","std")]), f'| {tot}')
print()
print('forced kernel of [A] on R_d^{par} (per irrep, multiplicity excess m_d - m_{d+6}):')
for d in range(1, 13):
    for par in (0, 1):
        m0 = M[(d, par)]; m1 = M[(d+6, 1-par)]
        exc = {k: m0[k]-m1[k] for k in m0 if m0[k]-m1[k] > 0}
        if exc: print(f'  d={d} par={par}:', {f'{a}x{b}': v for (a,b), v in exc.items()}, ' total forced dim', sum(v*chars[a]['e']*chars[b]['e'] for (a,b), v in exc.items()))
