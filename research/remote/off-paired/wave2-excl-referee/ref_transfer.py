#!/usr/bin/env python3
"""Referee transfer replay: take the EXACT rational quadrics J2 from the packet's Singular scripts (d{d}_c{c}_J2.sing),
reduce them modulo a FRESH prime, run msolve -g 2 (reduced GB, grevlex) and check that every variable has a pure power
among the leading monomials.  m-primary mod p for an ideal generated by the reductions of exact integer quadrics implies
m-primary over Q (Hilbert function over Q <= Hilbert function mod p), i.e. the affine cone V(J2) over C is {0}.
usage: python3 ref_transfer.py <prime> <sing file> [...]"""
import sys, re, subprocess, os
from fractions import Fraction
p = int(sys.argv[1])
for path in sys.argv[2:]:
    txt = open(path).read()
    m = re.search(r'ring r = 0, \(([^)]*)\), dp;', txt); names = [v.strip() for v in m.group(1).split(',')]; nt = len(names)
    body = re.search(r'ideal J2 = (.*?);\s*\n\s*ideal G', txt, re.S).group(1)
    polys = []
    for P in body.split(',\n'):
        P = P.strip().replace('\n', '')
        if not P: continue
        terms = []
        for t in re.findall(r'\(([-\d/]+)\)\*(t\d+)\*(t\d+)', P):
            c = Fraction(t[0]); cm = (c.numerator * pow(c.denominator, -1, p)) % p
            if cm == 0: continue
            terms.append(f'{cm}*{t[1]}^2' if t[1] == t[2] else f'{cm}*{t[1]}*{t[2]}')
        if terms: polys.append('+'.join(terms))
    if not polys:
        print(path, 'NO QUADRICS'); continue
    base = f'/tmp/hodge/referee/off-paired/transfer_{os.path.basename(path)[:-5]}_p{p}'
    open(base + '.ms', 'w').write(','.join(names) + '\n' + str(p) + '\n' + ',\n'.join(polys) + '\n')
    r = subprocess.run(['msolve', '-g', '2', '-f', base + '.ms', '-o', base + '.gb', '-t', '2', '-v', '0'], capture_output=True, text=True, timeout=900)
    gb = open(base + '.gb').read()
    i = gb.find('['); j = gb.rfind(']'); gpolys = [s.strip() for s in gb[i+1:j].replace('\n', '').split(',') if s.strip()]
    pure = {}
    unit = False
    for P in gpolys:
        first = P.split('+')[0]
        parts = first.split('*')[1:]
        if not parts: unit = True
        if len(parts) == 1:
            mm = re.match(r'(t\d+)\^(\d+)', parts[0]); pure[mm.group(1)] = min(pure.get(mm.group(1), 10**9), int(mm.group(2)))
    ok = all(v in pure for v in names)
    print(f'{os.path.basename(path)}: nt={nt} quadrics={len(polys)} GB size={len(gpolys)} unit={unit} pure powers={len(pure)}/{nt} -> {"M-PRIMARY mod p => m-primary over Q" if ok and not unit else "NOT m-primary (or unit ideal)"}')
